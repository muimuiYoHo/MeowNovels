import { 读开放资源, 读库 } from "./索引.js";
import { 解析时间, 解析长度, 归一化编码 } from "./工具.js";

function 匹配键(记录, 来源, 外部id, 卷) {
  return 记录.来源 === 来源
    && String(记录.外部id) === String(外部id)
    && String(记录.卷) === 卷;
}

export function 查询结果(参数) {
  const 来源 = String(参数.来源 ?? "").trim();
  const 外部id = String(参数.外部id ?? "").trim();
  const 卷 = 参数.全文 ? "0" : String(参数.卷 ?? "0");
  if (!来源 || !外部id) return { 成功: false, 错误: "缺少来源或外部id" };

  const 开放 = 读开放资源().find((记录) =>
    匹配键(记录, 来源, 外部id, 卷) && Number(记录.开放状态) === 1);

  if (!开放) {
    return {
      成功: true,
      状态: "不存在",
      消息: "库中没有该资源或未开放",
      下载方案: "官方",
    };
  }

  const 库行 = 读库().find((记录) => Number(记录.Mui轻小说id) === Number(开放.Mui轻小说id));
  if (!库行) return { 成功: true, 状态: "索引异常", 消息: "开放资源缺少对应库记录，人工会处理" };
  

  const 请求时间 = 解析时间(参数.外部更新时间);
  const 请求长度 = 解析长度(参数.全文长度);
  const 本地时间 = 解析时间(库行.外部更新时间);
  const 本地长度 = 解析长度(库行.全文长度);
  const 落后时间 = 请求时间 && 本地时间 ? 请求时间.getTime() > 本地时间.getTime() : false;
  const 落后长度 = 请求长度 !== null && 本地长度 !== null ? 请求长度 > 本地长度 : false;

  let 状态;
  let 消息;
  if (!落后时间 && !落后长度) {
    状态 = "最新";
    消息 = "资源是最新的喵，可直接下载喵（￣︶￣）↗　";
  } else if (落后时间 && 落后长度) {
    状态 = "过时";
    消息 = "资源已过时（外部更新时间与全文长度均落后），请前往官方下载后允许工具上传以更新资源";
  } else {
    状态 = "需人工";
    消息 = "资源部分落后（更新时间与长度不一致），请允许上传 .mui 文件交由缪缪大人判断";
  }

  const 结果 = {
    成功: true,
    状态,
    消息,
    资源: {
      Mui轻小说id: 开放.Mui轻小说id,
      名称: 库行.名称 ?? 开放.名称,
      来源,
      外部id,
      卷,
      库: {
        全文长度: 库行.全文长度,
        外部更新时间: 库行.外部更新时间,
        本地更新时间: 库行.本地更新时间,
        sha256: 库行.sha256,
      },
      请求: {
        全文长度: 参数.全文长度 ?? "",
        外部更新时间: 参数.外部更新时间 ?? "",
      },
    },
  };

  if (状态 === "最新") {
    const 编码 = 归一化编码(参数.编码);
    const 语言 = 参数.语言 === "繁" ? "繁" : "简";
    结果.下载 = {
      方式: "后端",
      url: `/下载?行为=下载&muiid=${encodeURIComponent(开放.Mui轻小说id)}&来源=${encodeURIComponent(来源)}&外部id=${encodeURIComponent(外部id)}&卷=${encodeURIComponent(卷)}&编码=${编码}&语言=${语言}`,
    };
  } else {
    结果.下载 = { 方式: "官方" };
  }

  return 结果;
}