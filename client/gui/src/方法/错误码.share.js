// 全局错误码表和统一的失败出口
//
// 约定 E-域-三位序号
//   域按 出问题后该去查什么 划分 不按代码文件划分
//     按模块分域会产生噪音 除了让表变长没有任何用
//   序号只增不改 码一旦发出去就是对外契约 改码=毁约
//
// 说明末尾统一写 该去查什么 错误码是用来缩短排查路径的
// 只写出错了等于没说 001 和 003 看着都像找不到文件
// 但一个去查部署一个改代码 那才是该拆开的地方

export const 错误码 = {
    // ── 数据读取和写入 方法/获取信息
    找不到数据文件: 'E-DATA-001', // 私有空间和初始数据都没有它 → 查数据/部署
    找不到信息字段: 'E-DATA-002', // 文件读到了但少字段       → 查那个 JSON
    未登记数据文件: 'E-DATA-003', // 名字不在表里             → 写错了 / 忘了登记
    写入数据失败: 'E-DATA-004', // 落盘被拒/抛错            → 查私有空间权限与路径
    找不到资源文件: 'E-DATA-005', // 数据里的相对路径在打包资源里找不到 → 查路径写法 / 资源有没有放进去

    // ── 浏览器环境 方法/浏览器信息
    未登记浏览器信息: 'E-BROWSER-001', // 名字不在表里      → 查表 / 拼错
    浏览器信息不可用: 'E-BROWSER-002', // 浏览器不支持或拒绝 → 查该项在目标内核上的支持情况

    // ── 界面调用 方法/吐司
    未登记吐司类型: 'E-UI-001', // 类型不在表里 → 查调用点 / 补类型表
    原生吐司不可用: 'E-UI-002', // 没有桥或调用失败 已降级私有吐司 查平台或桥有没有挂上
};

const 错误说明 = {
    [错误码.找不到数据文件]: '私有空间和打包的初始数据里都没有它 —— 查数据/部署',
    [错误码.找不到信息字段]: '文件读到了，但里面少这个字段 —— 查那个 JSON',
    [错误码.未登记数据文件]: '数据文件表里没有这个名字 —— 写错名字，或者新文件忘了登记',
    [错误码.写入数据失败]: '写私有空间被拒或抛错 —— 查权限与路径（安卓上路径必须用 / 拼接）',
    [错误码.找不到资源文件]: '数据里写的相对路径在打包资源里对不上 —— 查路径写法，或那个文件有没有放进 初始数据/',
    [错误码.未登记浏览器信息]: '浏览器信息表里没有这一项 —— 写错名字，或者该项还没做',
    [错误码.浏览器信息不可用]: '浏览器不给这个值 —— 查该项在目标内核上的支持情况',
    [错误码.未登记吐司类型]: '吐司类型表里没有这个名字 —— 查调用点，或者给类型表补一行',
    [错误码.原生吐司不可用]: '没有原生 Toast 桥、或调用失败 —— 已降级；查平台，以及 gen/ 的 MainActivity 有没有挂桥',
};

// 最近错误 给诊断用的一次性缓冲区 新的在后
// 全局共享 排查时不必挨个模块问 你这边有没有出错
const 最近错误 = [];
const 最近错误上限 = 50;

// 统一的失败出口
//
// 取值失败不该让页面崩 缺一个字段页面空一格远好过整页白屏
// 所以这里返一个安全的兜底值 错误码走旁路 最近错误加 dev 警告
// 不塞进返回值 调用点才不用每次都解构判断
//
// 想严格处理的调用方 查 读取最近错误 或自己在外面判空串
export function 返回错误(码, 详情, 兜底值 = '') {
    const 说明 = 错误说明[码] ?? '未登记的错误码';
    最近错误.push({ 码, 说明, 详情, 时刻: Date.now() });
    if (最近错误.length > 最近错误上限) 最近错误.shift();
    if (import.meta.env.DEV) {
        console.warn(`${码}（${说明}）：${详情}`);
    }
    return 兜底值;
}

// 诊断出口 最近发生过的错误 新的在后
export function 读取最近错误() {
    return 最近错误.map((项) => ({ ...项 }));
}

// 排查完一轮后想清空 比如切页前 就调它
export function 清空最近错误() {
    最近错误.length = 0;
}
