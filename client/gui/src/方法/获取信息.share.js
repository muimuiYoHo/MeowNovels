import { 错误码, 返回错误 } from './错误码';
export { 错误码, 返回错误, 读取最近错误, 清空最近错误 } from './错误码';

// 「按文件 + 字段」取应用数据的统一入口。
//
// 两层来源，顺序不能反：
//   1. 私有空间：Rust 的 app_local_data_dir()/files（见 platform.android.rs 的 `私有空间根目录`）。
//      首次启动由 `初始化应用存储` 把初始数据释放进去；用户改过之后以盘上为准。
//   2. 编译期打包进前端的 `资源/初始数据/**`。
//
// 兜底为什么读同一份 JSON 而不写死常量：Rust 的 `include_dir!` 嵌的就是这个目录，
// 两边同源。写死常量迟早漂移 —— 改名要改两处，还容易只改一处。
//
// ⚠️ 兜底不是可有可无的，而且不能只在「整个文件读不到」时才兜底。本机实测两个坑：
//   · `初始化应用存储` 的幂等判据是**顶层目录**是否存在 —— `数据/` 已存在就整棵跳过，
//     所以往初始数据里**新增**的文件在老设备上不会被释放（实测私有空间 `数据/本应用/`
//     里只有 `状态.json`，没有 `基本信息.json`）。
//   · 私有空间的 `设置/应用设置.json` 还是旧结构（`常规` 是个空数组，没有 `语言`）。
//   结论：逐字段 `??` 兜底 ——「文件读到了」不等于「字段在」。

// ── 数据文件表 ──
//
// **一个文件一行**，不是每个字段一行 —— 这是有意的：
// 字段会一直加、文件基本不会，所以表只登记到「文件」这一层，字段名直接写在调用处。
// 把字段也塞进来，表会迅速膨胀，而收益只是省一次打字；调用点反而变得要反查。
//
// 值同时是「私有空间里的相对路径」和「`初始数据/` 下的相对路径」，两层来源靠它对齐。
const 数据文件 = {
    基本信息: '数据/本应用/基本信息.json',
    状态: '数据/本应用/状态.json',
    账号: '数据/用户资源/账号.json',
};

// ── 打包的初始数据 ──
//
// 编译期内联成一张表，**同步**就能取到（组件首帧要用）。
// 用 glob 而不是逐个 import：以后往 初始数据/ 里加文件不必回来改这里。
// ⚠️ 必须用 ?raw 拿原始字符串、自己解析，不能让 Vite 按 JSON 处理这个目录：
//    初始数据里会有**空文件**（`数据/用户资源/账号.json` 就是个空占位），
//    空内容不是合法 JSON → Vite 的 json 插件解析失败 → 整个模块加载崩，
//    页面直接弹错误覆盖层（实测踩到）。
//    ?raw 下坏文件只在运行时丢掉它自己，不影响别的字段。
const 初始数据表 = import.meta.glob('../资源/初始数据/**/*.json', {
    eager: true,
    query: '?raw',
    import: 'default',
});

// 把 glob 的键（形如 '../资源/初始数据/数据/本应用/基本信息.json'）索引成业务路径
// （'数据/本应用/基本信息.json'）—— 调用处就不用关心相对层级要数几个 `../` 了。
const 初始数据索引 = {};
for (const [键, 原始] of Object.entries(初始数据表)) {
    const 位置 = 键.indexOf('初始数据/');
    if (位置 < 0) continue;
    const 业务路径 = 键.slice(位置 + '初始数据/'.length);
    try {
        初始数据索引[业务路径] = JSON.parse(原始);
    } catch {
        // 空文件 / 语法错误 → 当作「这份初始数据不存在」，调用方自会退回别的来源。
        // 这属于**构建期的数据问题**，不进 最近错误（那是给运行期取值用的）。
        初始数据索引[业务路径] = null;
        console.warn(`[获取信息] 初始数据 ${业务路径} 不是合法 JSON，已忽略`);
    }
}

const 设置路径 = '设置/应用设置.json';

function 初始数据(路径) {
    return 初始数据索引[路径] ?? null;
}

function 初始语言() {
    return 初始数据(设置路径)?.常规?.语言 ?? '';
}

// 字段值有两种形态：
//   · 普通值（'v0.6.2'、'喵喵喵'、'1971/1/1/0/0'）—— 原样返回
//   · 多语言表（应用名称: {中, 繁, 日, 英}）—— 按设置里的语言挑一个
// 多语言表的 key 是**单字**，而设置里写的是语言全称（中文 / 日语 …），
// 靠「key 恰好是语言名的首字」对齐。三级匹配、逐级放宽：
//   1. 设置值本身就是 key —— 以后设置里改成存 '中' 也能直接用
//   2. key 是设置值的开头 —— '中文' → '中'、'繁体中文' → '繁'
//   3. 都不匹配就取第一项 —— 宁可显示点东西，也别空着
function 按语言取(表, 语言) {
    const 全部键 = Object.keys(表);
    if (!全部键.length) return '';
    if (语言 && 全部键.includes(语言)) return 表[语言];
    if (语言) {
        const 命中 = 全部键.find((键) => 语言.startsWith(键));
        if (命中) return 表[命中];
    }
    return 表[全部键[0]];
}

function 本地化(值, 语言) {
    if (值 === null || 值 === undefined) return '';
    // 数组也是 object，但它是值本身，不该被当成多语言表
    if (typeof 值 !== 'object' || Array.isArray(值)) return 值;
    return 按语言取(值, 语言);
}

// 同一个文件一场会话只读一次。并发的多个字段调用共享同一个 Promise，
// 所以「基本信息 + 状态」这种同文件的读写只会各走一趟 IPC。
const 读取缓存 = new Map();

function 读私有文件(路径) {
    if (读取缓存.has(路径)) return 读取缓存.get(路径);
    // '数据/本应用/基本信息.json' → 子目录 '数据/本应用' + 文件名 '基本信息.json'
    // （读取文件 只在没带 .json 时才补后缀，带了就原样用）
    const 斜杠 = 路径.lastIndexOf('/');
    const 子目录 = 斜杠 < 0 ? 私有目录.数据 : 路径.slice(0, 斜杠);
    const 文件名 = 斜杠 < 0 ? 路径 : 路径.slice(斜杠 + 1);
    const 承诺 = 读取文件(子目录, 文件名, null);
    读取缓存.set(路径, 承诺);
    return 承诺;
}

// 语言每次本地化都要用，缓存成 Promise；整场会话里只读一次盘
let 语言承诺 = null;
function 取语言() {
    if (!语言承诺) {
        语言承诺 = (async () => {
            const 盘上 = await 读私有文件(设置路径);
            return 盘上?.常规?.语言 ?? 初始语言();
        })();
    }
    return 语言承诺;
}

// 取一个字段的当前值。文件名必须是 数据文件 表里登记过的：
//     获取信息('基本信息', '软件版本')
//     获取信息('状态', '上次检查时间')
export async function 获取信息(文件名, 字段) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        return 返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里 —— 名字写错了，还是新文件忘了登记？`);
    }
    const [盘上, 语言] = await Promise.all([读私有文件(路径), 取语言()]);
    const 打包的 = 初始数据(路径);
    // 「两份来源一份都没有」和「文件有、缺字段」是两个不同的错误码，不能混成一个
    if (盘上 === null && 打包的 === null) {
        return 返回错误(错误码.找不到数据文件, `私有空间和初始数据里都没有「${路径}」`);
    }
    const 原始 = 盘上?.[字段] ?? 打包的?.[字段];
    if (原始 === undefined) {
        return 返回错误(错误码.找不到信息字段, `「${路径}」里没有字段「${字段}」`);
    }
    return 本地化(原始, 语言);
}

// 同一件事的**同步**版：只用打包的初始数据、零 IPC。
// 给组件在 data() 里起手用 —— 首帧就有内容，不会空一下再被异步值顶掉。
// 错误处理与 获取信息 完全一致，所以两边报的码可以对照着看。
export function 初始信息(文件名, 字段) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        return 返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里 —— 名字写错了，还是新文件忘了登记？`);
    }
    const 打包的 = 初始数据(路径);
    if (打包的 === null) {
        return 返回错误(错误码.找不到数据文件, `初始数据里没有「${路径}」`);
    }
    const 原始 = 打包的?.[字段];
    if (原始 === undefined) {
        return 返回错误(错误码.找不到信息字段, `「${路径}」里没有字段「${字段}」`);
    }
    return 本地化(原始, 初始语言());
}

// 用户改过设置（比如换了语言）之后调一下：丢掉缓存，下次重新读盘。
// 不调也不会错，只是语言会沿用旧值直到重启。
export function 信息缓存失效() {
    读取缓存.clear();
    语言承诺 = null;
}

// ── 实体（整份）读写 ──
//
// 「字段级」接口解决的是「读一个名字已知的字段」。但账号这类数据的 key 是
// **用户可增删的**（平台名），字段级接口不够用 —— 得按「份」读写。
//
// ⚠️ 实体级的兜底语义与字段级**不同**，这是有意的：
//   · 字段级 = 逐字段 `盘上 ?? 打包的` —— 盘上缺哪个字段就补哪个。
//     因为「往初始数据里新增的文件不会释放到老设备」，必须逐字段兜底。
//   · 实体级 = **整体优先**，盘上有就整份用盘上的，一个字段都不从初始数据补。
//     否则用户删掉的条目会被初始数据「复活」—— 和「初始化应用存储」按顶层目录
//     判幂等那个坑同源（已踩过一次）。
export async function 读取实体(文件名) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里 —— 名字写错了，还是新文件忘了登记？`);
        return null;
    }
    const 盘上 = await 读私有文件(路径);
    if (盘上 !== null && 盘上 !== undefined) return 盘上;

    const 打包的 = 初始数据(路径);
    if (打包的 === null) {
        返回错误(错误码.找不到数据文件, `私有空间和初始数据里都没有「${路径}」`);
        return null;
    }
    return 打包的;
}

// 同一件事的**同步**版，只用打包的初始数据（组件首帧用）。
export function 初始实体(文件名) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里`);
        return null;
    }
    const 打包的 = 初始数据(路径);
    if (打包的 === null) {
        返回错误(错误码.找不到数据文件, `初始数据里没有「${路径}」`);
        return null;
    }
    return 打包的;
}

// 把一份数据落盘。`读私有文件` 收的是「子目录 + 文件名」两个参数，这里做同样的拆分，
// 保证「读哪」和「写哪」走的是同一条路径规则。
async function 写回(路径, 数据) {
    const 斜杠 = 路径.lastIndexOf('/');
    const 子目录 = 斜杠 < 0 ? 私有目录.数据 : 路径.slice(0, 斜杠);
    const 文件名 = 斜杠 < 0 ? 路径 : 路径.slice(斜杠 + 1);
    try {
        await 写入文件(子目录, 文件名, 数据);
        // 写完必须让缓存失效：缓存里存的是 Promise，不删的话下一次读拿到的还是旧值
        读取缓存.delete(路径);
        return true;
    } catch (错误) {
        返回错误(错误码.写入数据失败, `写「${路径}」失败：${错误?.message ?? 错误}`);
        return false;
    }
}

// 增 / 改一个字段。内部是「读 → 改 → 写」，调用方不必自己先读一遍。
export async function 保存信息(文件名, 字段, 值) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里`);
        return false;
    }
    const 现有 = (await 读取实体(文件名)) ?? {};
    return 写回(路径, { ...现有, [字段]: 值 });
}

// 删一个字段（账号页的「登出」就是删掉那个平台的条目）。
// 本来就没有时直接返回成功 —— 「删掉不存在的东西」已经是目标状态，不必报错。
export async function 删除信息(文件名, 字段) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里`);
        return false;
    }
    const 现有 = (await 读取实体(文件名)) ?? {};
    if (!Object.prototype.hasOwnProperty.call(现有, 字段)) return true;
    const 新的 = { ...现有 };
    delete 新的[字段];
    return 写回(路径, 新的);
}

// 整份覆盖。给「清空」这类一次改多个字段的场景 —— 逐条调用 删除信息 会多读写好几趟盘。
export async function 替换实体(文件名, 数据) {
    const 路径 = 数据文件[文件名];
    if (!路径) {
        返回错误(错误码.未登记数据文件, `「${文件名}」不在 数据文件 表里`);
        return false;
    }
    return 写回(路径, 数据);
}

// ── 数据里的资源路径 → 可加载的地址 ──
//
// 数据里存的是**相对路径**（如 `../账号头像/1.jpg`），不能直接塞进 <img src>：
// 那是私有空间里的相对位置，而界面首屏用的是**打包资源**。
//
// 基准约定：相对 `初始数据/数据/用户资源/`。
// 实测数据里写的是 `../账号头像/1.jpg`、`../个人头像/x.jpg`，而文件其实放在
// `初始数据/数据/用户资源/账号头像/`、`.../个人头像/` —— 是**同级的兄弟目录**，
// 那个 `../` 是多余的。所以这里把开头的 `./`、`../` 全部剥掉再查，两种写法都能命中。
//
// 两个来源，**私有优先**（和「盘上优先」的既有约定一致）：
//   1. 私有空间 `数据/用户资源/` —— 用户换过的头像（由 `保存私有资源` 写进去）
//   2. 打包的 `初始数据/数据/用户资源/` —— 出厂自带的那几张
// 数据里记的路径（`../账号头像/3.jpg`）两边**同名同构**，所以私有侧一个文件就自然盖住出厂那张。
// ⚠️ 私有资源要读文件、是**异步**的，而这个函数必须**同步**（模板里直接调）。
//    所以走「预载 + 查表」：组件挂载时 `await 预载私有资源(名)` 把内容填进下面的缓存，
//    之后 `资源地址` 就能同步命中。没预载到就解析不出来 → 调用方要有兜底图。
const 用户资源表 = import.meta.glob('../资源/初始数据/数据/用户资源/**/*.{jpg,jpeg,png,webp,gif,svg}', {
    eager: true,
    import: 'default',
});

// 私有资源内容缓存：`'账号头像/3.jpg'` → data URL
const 私有资源缓存 = new Map();

export function 资源地址(路径) {
    if (!路径) return '';
    const 文本 = String(路径);
    // 已经是能直接用的地址就别去资源表里找了。
    // 换头像早先存的是压缩过的 data URL（见 方法/文件访问），它本身就是最终地址；
    // 现在改成落文件 + 存路径了，但**旧数据里还有 data URL**，所以这条得留着。
    if (/^(data:|blob:|https?:)/.test(文本)) return 文本;
    const 净 = 文本.replace(/^(\.\.?\/)+/, '');
    // 1. 私有优先 —— 用户换过的头像要盖住出厂那几张
    const 私有 = 私有资源缓存.get(净);
    if (私有) return 私有;
    // 2. 打包资源
    const 地址 = 用户资源表[`../资源/初始数据/数据/用户资源/${净}`];
    if (!地址) {
        返回错误(错误码.找不到资源文件, `「${路径}」→ 私有空间和打包资源里都没有「${净}」`);
        return '';
    }
    return 地址;
}

// 把一张私有资源读进上面的缓存（异步）。返回是否读到。
// 调用方在组件挂载时对「解析不出地址的头像」调它，读完后自己替换一次响应式数据即可重渲染。
export async function 预载私有资源(相对路径) {
    const 净 = String(相对路径 ?? '').replace(/^(\.\.?\/)+/, '');
    if (!净) return false;
    if (私有资源缓存.has(净)) return true;
    // 打包资源里已有的（出厂自带那几张）就不必白读一趟盘了
    if (用户资源表[`../资源/初始数据/数据/用户资源/${净}`]) return false;
    const 内容 = await 读取文本(私有目录.用户资源, 净, '');
    if (!内容) return false;
    私有资源缓存.set(净, 内容);
    return true;
}

// 从 data URL 的**实际格式**推扩展名。**只认 jpg / png** ——
// 我们自己产出的永远是 JPEG（`压缩图片` 统一 canvas → image/jpeg），
// 只有「压缩失败、退回原样」那条路才可能落到别的格式上。
// 返回 '' = 不支持。最典型的是 HEIC（手机拍的默认格式）：WebView 解不开、
// 压不了，那就更不能原样存下来 —— 存了也是个打不开的文件。
export function 图片扩展名(data地址) {
    const 类 = (/^data:image\/([a-z0-9.+-]+)/i.exec(String(data地址 ?? ''))?.[1] ?? '').toLowerCase();
    if (类 === 'jpeg' || 类 === 'jpg') return 'jpg';
    if (类 === 'png') return 'png';
    return '';
}

// 把一张图片（data URL）落进私有空间，返回**该写进数据的相对路径**。
// 换头像走这条：JSON 里只留路径，图片本体单独成文件 ——
// 否则一张头像几十万字符全塞进 JSON，每次落盘都要重写整份、还很难打开看。
// `基础名` **不带扩展名**（如 `'账号头像/3'`），扩展名由 data URL 的实际格式决定，
// 所以文件名和内容不会名不副实。返回 '' = 没存成（参数缺失，或格式不在 jpg / png 之列）。
export async function 保存私有资源(基础名, data地址) {
    const 扩展 = 图片扩展名(data地址);
    if (!基础名 || !扩展) return '';
    const 文件名 = `${基础名}.${扩展}`;
    await 写入文本(私有目录.用户资源, 文件名, data地址);
    // 顺手进缓存：刚换的头像立刻能显示，不必等下一次读盘
    私有资源缓存.set(文件名, data地址);
    return `../${文件名}`;
}

// 删掉一张私有资源，并把缓存里的也清掉（不然后面还会从缓存里读出来）。
// 登出 / 清空账号 / 换头像前都要用它 —— 否则私有空间会攒下一堆没人引用的孤儿文件。
// 文件本来就不存在算成功（见 Rust 的 `删除文件`）。
export async function 删除私有资源(相对路径) {
    const 净 = String(相对路径 ?? '').replace(/^(\.\.?\/)+/, '');
    if (!净) return false;
    私有资源缓存.delete(净);
    try {
        await 删除文件(私有目录.用户资源, 净);
        return true;
    } catch (错误) {
        // PC 端存储还没实现 → 删不掉。不抛：这是清理动作，失败顶多留个文件，
        // 不该把「登出」这条主流程带崩。记进 最近错误 就好。
        返回错误(错误码.写入数据失败, `删资源「${净}」失败：${错误?.message ?? 错误}`);
        return false;
    }
}
