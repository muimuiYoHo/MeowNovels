// 横向翻页：三页轨道的跟手平移 + 翻页判定。
//
// 越界拉伸回弹已分离到 拉伸回弹.android.js。本模块只负责：
//   · 触摸序列与手势方向判定（本次手势是「横向」还是「纵向」）
//   · 横向跟手位移（拖动位移）与松手时的翻页结算（距离 / 速度）
//   · 轨道的横向平移样式
// 纵向移动与横向越界都**委托给拉伸回弹模块** —— 它自己判断能不能拉伸、并按铁律
// 锁定本次手势的拉伸方向（见 拉伸回弹.android.js 模块头部的说明）。
//
// 为什么走 touch 通道而不是 pointer 通道（真机实测，别再改回去）：
// 容器带 touch-action: pan-y 时，浏览器一旦把手势判定为横向 pan 就直接发 pointercancel
// 收回整条指针序列 —— 实测 pointermove 只到 1 次、后续 21 次全走 touchmove，
// pointer 通道上永远拿不到足够位移，横向翻页必然失效。
// 所以用 touch 事件旁路读位移，容器 touch-action 留 auto 把纵向滚动交还浏览器。
//
// ⚠️ 变量名一律写成完整词组（不用 首 / 末 / 速 这类单字）：本文件里同时存在
// 「手势方向」「手指位移」「页面索引」三套含义相近的量，单字名极容易看错。

import { 创建拉伸回弹, 初始拉伸状态 } from "./拉伸回弹.android";

// ── 翻页参数 ──
const 手势方向阈值 = 8; // 位移超过它才锁定手势方向（px）
const 翻页位移比例 = .22; // 位移超过视口宽的该比例就翻页
const 翻页速度阈值 = .5; // 或者速度超过它（px/ms）就翻页

// 初始状态。调用方拿它建 reactive 对象，再传给 创建滑动。
// 单独导出是为了让「状态形状」只有一个定义点，组件不必重复声明字段。
// 拉伸相关字段（下拉量/上拉量/右拉量/左拉量/跟手中）由拉伸回弹模块提供，这里合并进来 ——
// 对外仍然是「一个对象、一次 reactive」，组件不需要知道内部分了模块。
export function 初始状态() {
    return {
        当前页: 0,
        拖动位移: 0, // 横向跟手位移（px，正 = 往右拉）
        拖动中: false,
        ...初始拉伸状态(),
    };
}

// 创建一套滑动逻辑。方法只改传入的状态对象、不碰 DOM（DOM 直写都在拉伸回弹模块里）。
//
// 关于响应式：状态对象由调用方传入（用 vue 的 reactive(初始状态()) 建），模块只往它上面写字段。
// 千万别在模块内部自己造对象、再让外面用 Object.assign 替换掉「状态」字段 ——
// 那样闭包仍指向旧对象，Vue 监听的是新代理，两边永远不同步（踩过）。
export function 创建滑动({ 页数, 视口宽, 视口高, 取滚动盒, 取页元素, 状态 }) {
    if (!状态) throw new Error("创建滑动：必须传入状态对象");

    const 拉伸回弹 = 创建拉伸回弹({ 视口宽, 视口高, 取页元素, 取滚动盒, 状态 });

    // ── 本次手势的跟踪状态 ──
    let 跟踪触点标识 = null; // 只跟第一根按下的手指；null = 当前没有手势
    let 手势起始x = 0;
    let 手势起始y = 0;
    let 手势方向 = null; // "横向" / "纵向" / null（还没判定出来）
    let 上一次触点x = 0;
    let 上一次采样时刻 = 0;
    let 滑动速度 = 0; // px/ms，用于松手时的速度翻页
    // touchmove 的到达频率可能高于屏幕刷新频率。直接在每个事件里写响应式状态，
    // 一旦某一帧因合成层栅格化变慢，后续事件就会堆积，表现为整段手势持续掉帧。
    // 只保留最新坐标，每帧最多写一次状态。
    let 移动节流帧号 = 0;
    let 待处理触点x = 0;
    let 待处理触点y = 0;
    let 有未消费触点 = false;

    function 取视口宽() {
        return (typeof 视口宽 === "function" ? 视口宽() : 视口宽) || 360;
    }

    function 从事件取跟踪触点(触摸事件) {
        for (const 触点 of 触摸事件.touches) {
            if (触点.identifier === 跟踪触点标识) return 触点;
        }
        return null;
    }

    function 开始(触摸事件) {
        if (!触摸事件.touches || 触摸事件.touches.length !== 1) return;
        const 触点 = 触摸事件.touches[0];
        拉伸回弹.作废归零回调(); // 若上一次松手的归零还没跑完，先取消，避免它在新手势中途捣乱
        if (移动节流帧号) {
            cancelAnimationFrame(移动节流帧号);
            移动节流帧号 = 0;
        }
        有未消费触点 = false;

        跟踪触点标识 = 触点.identifier;
        手势起始x = 触点.clientX;
        手势起始y = 触点.clientY;
        上一次触点x = 触点.clientX;
        上一次采样时刻 = performance.now();
        滑动速度 = 0;
        手势方向 = null;
        状态.拖动中 = false;
        状态.拖动位移 = 0;

        // 清方向锁 + 复位 DOM + 关原生 overscroll + 固定滚动上限 + 跟手中 = true
        拉伸回弹.手势开始();
    }

    function 移动(触摸事件) {
        if (跟踪触点标识 === null) return;
        const 触点 = 从事件取跟踪触点(触摸事件);
        if (!触点) return;

        待处理触点x = 触点.clientX;
        待处理触点y = 触点.clientY;
        有未消费触点 = true;
        if (!移动节流帧号) 移动节流帧号 = requestAnimationFrame(消费待处理触点);
    }

    function 消费待处理触点() {
        移动节流帧号 = 0;
        if (!有未消费触点 || 跟踪触点标识 === null) return;
        有未消费触点 = false;
        应用跟手位移(待处理触点x, 待处理触点y);
    }

    function 清空移动节流() {
        if (移动节流帧号) {
            cancelAnimationFrame(移动节流帧号);
            移动节流帧号 = 0;
        }
        // 结束/取消前先消费最后一个坐标，避免 rAF 尚未执行时丢掉末端位移。
        if (有未消费触点 && 跟踪触点标识 !== null) {
            有未消费触点 = false;
            应用跟手位移(待处理触点x, 待处理触点y);
        }
        有未消费触点 = false;
    }

    function 应用跟手位移(触点x, 触点y) {
        const 横向位移 = 触点x - 手势起始x;
        const 纵向位移 = 触点y - 手势起始y;

        // 首次超过方向阈值时锁定手势方向，之后本次手势内不再改
        if (!手势方向) {
            if (Math.abs(横向位移) < 手势方向阈值 && Math.abs(纵向位移) < 手势方向阈值) return;
            手势方向 = Math.abs(横向位移) > Math.abs(纵向位移) ? "横向" : "纵向";
            状态.拖动中 = 手势方向 === "横向";
            if (手势方向 === "纵向") {
                // 纵向：彻底放掉翻页跟手，只可能走拉伸
                状态.拖动位移 = 0;
            }
        }

        if (手势方向 === "纵向") {
            拉伸回弹.处理纵向拉伸(纵向位移);
            return;
        }

        // ── 横向：滑动速度采样（用于松手时判定「快速滑动翻页」）──
        const 当前时刻 = performance.now();
        const 距上次采样间隔 = 当前时刻 - 上一次采样时刻;
        if (距上次采样间隔 > 0) 滑动速度 = (触点x - 上一次触点x) / 距上次采样间隔;
        上一次触点x = 触点x;
        上一次采样时刻 = 当前时刻;

        const 是首页 = 状态.当前页 === 0;
        const 是末页 = 状态.当前页 === 页数 - 1;

        // 越界（首页右拉 / 末页左拉）交给拉伸回弹模块决定：
        // 它会在「够阈值且贴边」时锁定方向并接管；不接管（含手指已反向拉回）
        // 就返回 false，继续走正常跟手平移。
        if ((是首页 && 横向位移 > 0) || (是末页 && 横向位移 < 0)) {
            if (拉伸回弹.处理横向越界拉伸(横向位移, 是首页, 是末页)) {
                状态.拖动位移 = 0; // 拉伸接管 → 不做跟手平移
                return;
            }
        }
        状态.拖动位移 = 横向位移;
    }

    function 结束() {
        清空移动节流();
        const 手势曾在拖动 = 状态.拖动中;
        跟踪触点标识 = null;
        手势方向 = null;
        状态.拖动中 = false;

        if (!手势曾在拖动) {
            状态.拖动位移 = 0;
            拉伸回弹.松手归位();
            return;
        }

        const 翻页位移阈值 = 取视口宽() * 翻页位移比例;
        const 当前跟随位移 = 状态.拖动位移;
        let 目标页索引 = 状态.当前页;
        if (当前跟随位移 < -翻页位移阈值 || (当前跟随位移 <= 0 && 滑动速度 < -翻页速度阈值)) {
            目标页索引 = 状态.当前页 + 1;
        } else if (当前跟随位移 > 翻页位移阈值 || (当前跟随位移 >= 0 && 滑动速度 > 翻页速度阈值)) {
            目标页索引 = 状态.当前页 - 1;
        }
        目标页索引 = Math.min(页数 - 1, Math.max(0, 目标页索引));

        状态.拖动位移 = 0;
        状态.当前页 = 目标页索引;
        // 放在最后：让上面这些状态变更和「开过渡」一起进同一次 flush，
        // 再由 readback 钉死「起点 = 当前拉伸态」，然后才归零。
        拉伸回弹.松手归位();
    }

    function 取消() {
        清空移动节流();
        跟踪触点标识 = null;
        手势方向 = null;
        状态.拖动中 = false;
        状态.拖动位移 = 0;
        拉伸回弹.松手归位();
    }

    // 点导航栏切页：直接跳，不做动画中间态
    function 切到(页索引) {
        取消();
        拉伸回弹.作废尺寸缓存();
        状态.当前页 = Math.min(页数 - 1, Math.max(0, 页索引));
    }

    // ── 样式输出 ──

    // 轨道的横向平移
    function 轨道样式() {
        const 轨道位移 = -状态.当前页 * 取视口宽() + 状态.拖动位移;
        return { transform: "translate3d(" + 轨道位移 + "px, 0, 0)" };
    }

    // 每页的容器样式由拉伸回弹模块给出（transform 的拼装与过渡开关都在那边）
    function 页样式(页索引) {
        return 拉伸回弹.页面样式(页索引);
    }

    function 尺寸失效() {
        拉伸回弹.作废尺寸缓存();
    }

    return { 状态, 开始, 移动, 结束, 取消, 切到, 轨道样式, 页样式, 尺寸失效 };
}
