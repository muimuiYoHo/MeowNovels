// 翻页 协议 §4.1 的 喵.工具.翻页 间隔 限速 中止全归工具 源里不许自己写 setTimeout 防封

// 造一个 喵.工具.翻页
//
// 流式 每页 批次 页号 每抓完一页就回调一次
// 文库8 每页要间隔 5 到 6 秒 5 页全抓完得 20 秒以上 用户会以为卡死
// 有了它 首页解析完就能先显示出来
//
// 可中断 每页开始前查 信号.aborted 面板收起 切页 换词之后后面几页根本不该发出去
// 站点限速是按次算的 白抓几页既慢又容易被封
//
// 依赖 限速 发起网络请求 编码处理
export function 造翻页器({ 限速 = {}, 发起网络请求, 编码处理 } = {}) {
    // 能被 信号 提前打断的 sleep 否则中止后还要干等一个限速间隔
    function 可被信号打断的等待(毫秒, 信号) {
        return new Promise((完成) => {
            const 定时器 = setTimeout(完成, 毫秒);
            信号?.addEventListener?.('abort', () => {
                clearTimeout(定时器);
                完成();
            }, { once: true });
        });
    }

    return async function 翻页(配置 = {}) {
        const 起始页 = Number(配置.起始页 ?? 1);
        const 总页数 = Number(配置.总页数 ?? 1);
        const 页间隔 = Number(配置.间隔 ?? 限速.页面间隔 ?? 0);
        const 信号 = 配置.信号;
        const 结果 = [];
        // 这里只能用宿主侧的东西 记录日志 是 工具 对象上的方法 源才用它
        // 在 翻页 里直接喊会 ReferenceError 把整次翻页炸掉
        for (let 页 = 起始页; 页 <= 总页数; 页++) {
            if (信号?.aborted) {
                console.log(`[翻页] 第 ${页} 页前被中止（已拿到 ${结果.length} 条）`);
                break;
            }
            if (页间隔 > 0 && 页 > 起始页) {
                await 可被信号打断的等待(页间隔, 信号);
                if (信号?.aborted) {
                    console.log(`[翻页] 等待第 ${页} 页时被中止（已拿到 ${结果.length} 条）`);
                    break;
                }
            }
            const 响应 = await 发起网络请求(配置.取地址(页), 配置.请求选项 || {});
            const 批次 = 配置.解析(响应.文本 ?? (await 编码处理.文本解码(响应.原始, 'gbk'))) || [];
            结果.push(...批次);
            配置.每页?.(批次, 页);
        }
        return 结果;
    };
}
