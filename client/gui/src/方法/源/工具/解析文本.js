// 解析文本 协议 §4.1 的 喵.工具.解析文本 四个纯函数 源抠字段用
//
// 分清两个最容易用错的
//   剥离标签 只去尖括号 不动换行 不解实体 抠单个字段 作者 分类 字数
//   HTML转文本 还会把 br 和 p 这类块级标签变换行 解实体 压空行 解析正文

// 只认这 6 个实体 协议明说别指望完整表 其余原样留着
const 内容实体表 = { nbsp: ' ', amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" };

// 喵.工具.解析文本 协议 §4.1 四个方法名是契约 改一个字母就会让已写好的源崩掉
export const 解析文本 = {
    // 只去尖括号 不动换行 不解实体 抠单个字段用
    剥离标签(文本) {
        return String(文本 ?? '').replace(/<[^>]*>/g, '');
    },
    // 块级标签变换行 解实体 压连续空行 解析正文用
    HTML转文本(文本) {
        let 出 = String(文本 ?? '');
        出 = 出.replace(/<br\s*\/?>/gi, '\n');
        出 = 出.replace(/<\/(p|div|h[1-6]|li|tr)>/gi, '\n');
        出 = 出.replace(/<[^>]*>/g, '');
        出 = 解析文本.解码内容实体(出);
        return 出
            .replace(/[ \t\u00a0]+/g, ' ')
            .replace(/\n{3,}/g, '\n\n')
            .replace(/^\s+|\s+$/g, '');
    },
    // 只认这 6 个实体 见 内容实体表 其余原样留着
    解码内容实体(文本) {
        return String(文本 ?? '').replace(/&(#39|nbsp|amp|lt|gt|quot);/g, (整段, 名) => 内容实体表[名] ?? 整段);
    },
    // 取第 1 组 取不到返空串 免得每处都判 null
    正则过滤(文本, 正则, 组 = 1) {
        const 命中 = String(文本 ?? '').match(正则);
        return 命中 ? (命中[组] ?? '').trim() : '';
    },
};
