// 繁简转换 协议 §4.1 的 喵.工具.繁简转换 目前没有对照表
//
// 协议要求 方向为 原 时别调它 直接返原文 文库8 用不到
// 它的简繁由服务端 charset 决定 不是本地转换
//
// 所以这里直通加首次警告 而不是抛错 抛错会让整个源挂掉
// 而译文没转换只是降级 不该阻断

// 造一个 喵.工具.繁简转换
//
// 每次造各带一个 已警告过 标记 警告按源打一次 不是全进程一次
// 否则第二个用到它的源自始至终只有一句 warning 都不属于它 出了问题连线索都没有
export function 造繁简转换器() {
    let 已警告过 = false;
    return function 繁简转换(文本, 方向) {
        if (!已警告过) {
            已警告过 = true;
            console.warn(`[源工具] 繁简转换尚未实现对照表，本源起按原文返回（方向：${方向 ?? '未给'}）`);
        }
        return String(文本 ?? '');
    };
}
