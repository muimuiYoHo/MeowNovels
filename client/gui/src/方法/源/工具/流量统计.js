// 流量统计 只累加下载字节 按源隔离落盘 数据/网络/标识.json
//
// 落盘节流 1.5 秒合并一次 读小说一章一个请求 逐次写盘太浪费
import { 私有目录, 读取文件, 写入文件 } from '../../存储';

const 流量目录 = `${私有目录.数据}/网络`;
// 落盘节流间隔 这段时间内攒下的字节一次性并进去
const 合并写盘间隔 = 1500;

// 造一个流量记账户 给 设置 流量使用情况 用
// 选项 标识 落盘文件名就是它 空标识直接不记 匿名源没有归属
// 返 累加下载字节 返原响应 方便直接串在 return 上
export function 造流量记账户({ 标识 } = {}) {
    let 待落盘字节 = 0;
    let 落盘计时器 = null;

    // 真正写盘 把攒下的量并进 数据/网络/标识.json
    async function 把攒下的字节并进磁盘() {
        落盘计时器 = null;
        const 本次字节 = 待落盘字节;
        待落盘字节 = 0;
        if (!本次字节 || !标识) return;
        const 现值 = (await 读取文件(流量目录, 标识, null)) ?? {};
        现值.下载字节 = (现值.下载字节 ?? 0) + 本次字节;
        现值.更新时间 = new Date().toISOString();
        await 写入文件(流量目录, 标识, 现值);
    }

    // 把一次响应的体积记进待落盘 到点自动写盘
    // 返原响应 让调用方可以 return 累加下载字节 响应
    function 累加下载字节(响应) {
        const 字节数 = 响应?.原始?.length;
        if (字节数 && 字节数 > 0) {
            待落盘字节 += 字节数;
            if (!落盘计时器) 落盘计时器 = setTimeout(把攒下的字节并进磁盘, 合并写盘间隔);
        }
        return 响应;
    }

    return { 累加下载字节 };
}
