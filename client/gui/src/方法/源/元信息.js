// 源元信息的静态提取与校验 源协议 §6
//
// 为什么必须静态 不能执行源
//   列表页要在不执行任何第三方代码的前提下显示源 快也安全
//   执行源才能拿到的元信息 报错时已经晚了 那时用户看到的是一个打不开的源
//   而不是 第 12 行少了 版本 字段
//   导入时就要能校验 而导入时我们连跑都不敢跑它
//
// 所以 正则找入口 平衡括号扫描取字面量 剥注释 JSON.parse
// 全程不执行源里的任何一行代码

// 协议要求的必填字段
export const 必填字段 = ['协议', '标识', '名称', '版本', '能力'];

// 源允许暴露的方法名 §7 规则 1 与 能力 逐字相同
export const 允许的方法名 = [
    '资源搜索',
    '获取资源详情',
    '获取目标资源章节列表',
    '资源下载',
    '登录至源平台',
    '注册源平台账号',
    '取封面',
];

// 工具支持的协议版本 源声明的 协议 必须在这里面 否则拒载
export const 支持的协议 = ['日喵0.4'];

// 剥掉行注释和块注释 但保留其中的换行 行号不能跑
//
// 不能简单用正则剥 元信息里的值遍地是 https 开头的地址
// 那样会把 域名集 那行的后半截连引号一起吃掉 结果报 JSON 语法错误 真正的原因完全看不出来
// 所以逐字符走状态机 只在字符串外认注释
function 剥注释(文本) {
    let 出 = '';
    let 状态 = '代码';
    for (let i = 0; i < 文本.length; i++) {
        const 当前 = 文本[i];
        const 下一个 = 文本[i + 1];
        if (状态 === '代码') {
            if (当前 === "'" || 当前 === '"' || 当前 === '`') {
                状态 = '字符串';
                出 += 当前;
            } else if (当前 === '/' && 下一个 === '/') {
                状态 = '单行注释';
                i++;
            } else if (当前 === '/' && 下一个 === '*') {
                状态 = '块注释';
                i++;
            } else {
                出 += 当前;
            }
        } else if (状态 === '字符串') {
            if (当前 === '\\') {
                出 += 当前 + (下一个 ?? '');
                i++;
            } else {
                if (当前 === "'" || 当前 === '"' || 当前 === '`') 状态 = '代码';
                出 += 当前;
            }
        } else if (状态 === '单行注释') {
            // 注释内容丢掉 但换行要留着 行号全靠它
            if (当前 === '\n') {
                状态 = '代码';
                出 += '\n';
            }
        } else if (状态 === '块注释') {
            if (当前 === '*' && 下一个 === '/') {
                状态 = '代码';
                i++;
            } else if (当前 === '\n') {
                出 += '\n';
            }
        }
    }
    return 出;
}

// 某位置在第几行 从 1 起 提取器报错全用它
export function 取行号(文本, 位置) {
    let 行 = 1;
    for (let i = 0; i < 位置 && i < 文本.length; i++) {
        if (文本[i] === '\n') 行++;
    }
    return 行;
}

// 从源码文本里抠出 export const 元信息 这段字面量
// 用平衡括号扫描不用正则 能力是数组 下载模式是对象数组
// 正则匹配不到嵌套结构 而且会把后面的代码一起吃进来
//
// 返 片段 和 起始行 或 问题
export function 提取字面量(源码) {
    const 剥后 = 剥注释(源码);
    const 入口 = 剥后.match(/export\s+const\s+元信息\s*=\s*\{/);
    if (!入口) {
        return {
            问题: [
                {
                    字段: '元信息',
                    行: 1,
                    问题: '找不到 `export const 元信息 = {` —— 源必须有这个顶层导出（协议 §6）',
                },
            ],
        };
    }
    const 左括号 = 剥后.indexOf('{', 入口.index);
    // 平衡扫描 数字符串状态下的括号 字符串里的不算 元信息里没有 但别留坑
    let 深度 = 0;
    let 状态 = '代码';
    for (let i = 左括号; i < 剥后.length; i++) {
        const 当前 = 剥后[i];
        if (状态 === '字符串') {
            if (当前 === '\\') {
                i++;
            } else if (当前 === '"' || 当前 === "'") {
                状态 = '代码';
            }
            continue;
        }
        if (当前 === '"' || 当前 === "'") {
            状态 = '字符串';
        } else if (当前 === '{') {
            深度++;
        } else if (当前 === '}') {
            深度--;
            if (深度 === 0) {
                return { 片段: 剥后.slice(左括号, i + 1), 起始行: 取行号(剥后, 左括号) };
            }
        }
    }
    return {
        问题: [
            { 字段: '元信息', 行: 取行号(剥后, 左括号), 问题: '元信息的括号没闭合（少了 `}`）' },
        ],
    };
}

// 提取元信息
//
// 失败必须报行号 绝不静默返回 undefined
// 静默的代价是用户看到一个空白的源列表 而不知道哪一行写错了
//
// 返 对象 和 问题 两者只会有一个有内容
export function 提取元信息(源码) {
    const 取出的 = 提取字面量(源码);
    if (取出的.问题) return { 对象: null, 问题: 取出的.问题 };

    try {
        return { 对象: JSON.parse(取出的.片段), 问题: [] };
    } catch (错误) {
        // JSON.parse 的 message 里带 position N 换算成源码行号才有用
        const 命中 = String(错误.message).match(/position\s+(\d+)/i);
        const 位置 = 命中 ? Number(命中[1]) : 0;
        return {
            对象: null,
            问题: [
                {
                    字段: '元信息',
                    行: 取出的.起始行 + 取行号(取出的.片段, 位置) - 1,
                    问题: `不是合法的 JSON 字面量：${错误.message}`,
                },
            ],
        };
    }
}

// 校验元信息对象 协议 §6 必填严格 未知忽略
// 返 通过 和 错误
// 校验在字面量之外做 所以行号一律给 0 也就是只指字段不指位置
export function 校验元信息(对象, 起始行 = 1) {
    const 错误 = [];
    const 报 = (字段, 问题) => 错误.push({ 字段, 行: 起始行, 问题 });

    if (!对象 || typeof 对象 !== 'object' || Array.isArray(对象)) {
        return { 通过: false, 错误: [{ 字段: '元信息', 行: 起始行, 问题: '元信息必须是一个对象' }] };
    }
    for (const 字段 of 必填字段) {
        const 值 = 对象[字段];
        if (值 === undefined) {
            报(字段, `缺少必填字段「${字段}」（协议 §6 必填集：${必填字段.join(' / ')}）`);
        }
    }
    for (const 字段 of ['协议', '标识', '名称', '版本']) {
        if (对象[字段] !== undefined && typeof 对象[字段] !== 'string') {
            报(字段, `「${字段}」必须是字符串`);
        }
    }
    if (对象.能力 !== undefined) {
        if (!Array.isArray(对象.能力)) {
            报('能力', '「能力」必须是数组');
        } else {
            for (const 名 of 对象.能力) {
                if (!允许的方法名.includes(名)) {
                    报('能力', `不认识的能力「${名}」，只允许：${允许的方法名.join(' / ')}`);
                }
            }
        }
    }
    // 协议版本不匹配就是拒载 没有商量的余地
    if (typeof 对象.协议 === 'string' && !支持的协议.includes(对象.协议)) {
        报('协议', `源要「${对象.协议}」，本工具支持 ${支持的协议.join(' / ')}`);
    }
    if (对象.域名集 !== undefined && !Array.isArray(对象.域名集)) {
        报('域名集', '「域名集」必须是数组');
    }
    if (对象.权限 !== undefined && !Array.isArray(对象.权限)) {
        报('权限', '「权限」必须是数组');
    }
    return { 通过: 错误.length === 0, 错误 };
}

// 保留标识符静态检查 协议 §7 规则 4
//
// 为什么需要 源是 JS 模块 const { X } = 喵.工具 会把 X 引入源的作用域
// 源自己再声明同名就是 SyntaxError 或静默遮蔽
// 子命名空间只能防住 工具对象 和 源方法 撞名 防不住源自己解构出来的局部变量
// 所以必须显式列清单
//
// 做法很粗 扫顶层声明 误报率可以接受 报出来就是让人改名 漏报由运行期兜底
export function 检查保留标识符(源码) {
    const 剥后 = 剥注释(源码);
    const 保留 = ['喵', '元信息'];
    const 工具键 = [
        '发起网络请求', 'Cookie', '编码处理', '解析文本', '繁简转换', '翻页',
        '发起下载', '批量抓取', '取回封面', '记录日志', '源配置',
    ];
    const 错误 = [];
    for (const 名 of [...保留, ...工具键]) {
        // 只查声明形态 const let var function class 后面跟这个名字
        const 正则 = new RegExp(`(?:^|[\\s;{])(?:const|let|var|function|class)\\s+${名}\\b`, 'm');
        const 命中 = 剥后.match(正则);
        if (命中) {
            错误.push({
                字段: 名,
                行: 取行号(剥后, 命中.index),
                问题: `「${名}」是保留标识符，源不得用它声明任何东西（协议 §7）`,
            });
        }
    }
    return 错误;
}
