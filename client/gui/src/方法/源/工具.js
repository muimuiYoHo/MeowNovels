// 造 喵.工具 源能拿到的全部能力 源协议 §4.1
//
// 这里是宿主与源之间唯一的接触面 源不能自己访问网络 不能自己写文件
// 一切都得经过这个对象 协议 §2.1 铁律 所以
//   网络只经 发起网络请求 走原生层 绕开 WebView 的 CORS
//   落盘只经工具 源永远拿不到绝对路径
//   按 元信息.权限 裁剪 没授的能力直接是 undefined 调用即 TypeError
//
// 本文件只做装配和权限裁剪 每件能力按功能拆在 工具/ 目录里
//   工具/编码处理.js  文本和字节 GBK Big5 的编码方向要自己查表
//   工具/解析文本.js  剥离标签 HTML转文本 解实体 正则过滤
//   工具/繁简转换.js  暂无对照表 直通加首次警告
//   工具/凭据存取.js  cookie 的两份存储 凭据文件 和 CookieManager 与合并
//   工具/网络请求.js  普通请求 借隐藏 WebView 过挑战 域名白名单
//   工具/翻页.js      间隔 限速 可中止
//   工具/封面.js      取回封面并转成 data URL
//
// 工具对象上的字段名就是契约 协议 §4.1 那张表逐个列了
// 改一个字母就会让所有已写好的源崩掉 要改之前先看 docs/compose/spec/源协议.md §4

import { 编码处理, 归一编码名 } from './工具/编码处理';
import { 解析文本 } from './工具/解析文本';
import { 造繁简转换器 } from './工具/繁简转换';
import { 造凭据存取器 } from './工具/凭据存取';
import { 造网络请求器 } from './工具/网络请求';
import { 造翻页器 } from './工具/翻页';
import { 造流量记账户 } from './工具/流量统计';
import { 造封面取回器 } from './工具/封面';

// 工具实现版本 协议 §4
export const 工具版本 = '日喵0.4';

// 归一编码名 仍然从本模块对外 老引用不用改
export { 归一编码名 };

// 给某个源造一个工具对象
//
// 源信息 标识 元信息 配置读写
//   配置读写 是 读取 和 写入 由注册表那边提供 工具不碰注册表文件格式
// 返 喵对象 版本 工具 日志
export function 造工具(源信息 = {}) {
    const 标识 = 源信息.标识 || '';
    const 元信息 = 源信息.元信息 || {};
    const 域名集 = Array.isArray(元信息.域名集) ? 元信息.域名集 : [];
    const 限速 = 元信息.限速 || {};
    // 本源这一次会话的运行日志 记录日志 往里塞 页面会读它做诊断
    const 日志 = [];

    // ── 按功能造出各部件的实例 每个源各一份 互不串味
    const 凭据存取 = 造凭据存取器({ 标识, 日志 });
    const 流量记账 = 造流量记账户({ 标识 });
    const { 发起网络请求, 校验域名白名单 } = 造网络请求器({
        元信息,
        域名集,
        凭据存取,
        累加下载字节: 流量记账.累加下载字节,
    });

    const 工具 = {
        发起网络请求,
        编码处理,
        解析文本,
        Cookie: 凭据存取.Cookie工具,
        繁简转换: 造繁简转换器(),
        翻页: 造翻页器({ 限速, 发起网络请求, 编码处理 }),
        记录日志(文本) {
            const 行 = String(文本 ?? '');
            日志.push(行);
            // 走 console 是为了 devtools 和真机 logcat 能立刻看到
            // 源自己不许 console.log 协议 §2.1 那是绕开宿主
            console.log(`[源 ${标识}] ${行}`);
        },
        源配置: {
            获取(键, 默认值) {
                const 全部 = 源信息.读取配置?.() ?? {};
                return 全部[键] === undefined ? 默认值 : 全部[键];
            },
            async 设置(键, 值) {
                const 全部 = { ...(源信息.读取配置?.() ?? {}) };
                全部[键] = 值;
                await 源信息.写入配置?.(全部);
            },
            读取全部() {
                return { ...(源信息.读取配置?.() ?? {}) };
            },
        },
        取回封面: 造封面取回器({ 校验域名白名单 }),
    };

    // ── 按权限裁剪 协议 §4 §10
    // 没授的能力是 undefined 调用即 TypeError 让源在开发期就崩
    // 而不是静默地什么都拿不到
    const 权限 = Array.isArray(元信息.权限) && 元信息.权限.length
        ? 元信息.权限
        : ['网', '存·写', '凭据·本源', '配置·本源'];
    if (!权限.includes('网')) {
        工具.发起网络请求 = undefined;
        工具.取回封面 = undefined;
    }
    if (!权限.includes('凭据·本源')) 工具.Cookie = undefined;
    if (!权限.includes('配置·本源')) 工具.源配置 = undefined;

    return { 版本: 工具版本, 工具, 日志 };
}
