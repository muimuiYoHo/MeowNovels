// 源的加载与调用 搜索页的入口
//
// 这里只做 拿注册表 读源文件 加载 调方法 这条链 不碰 UI
// 书源设置页那边有自己的一套 含注册表自愈

import { 私有目录, 读取文件, 读取文本 } from '../存储';
import { 提取元信息, 校验元信息, 检查保留标识符 } from './元信息';
// 写显式 .js 工具.js 旁边还有个同名目录 工具/ 不带扩展名两条路都成立 交给解析器猜不如写死
import { 造工具 } from './工具.js';

const 源目录 = `${私有目录.数据}/源`;
const 注册表文件 = '源注册';

// 已加载源缓存 key 是文件名 免得每次搜索都重新 blob import 一遍
const 缓存 = new Map();

// 本次会话试过登录且失败的源标识 免得每敲一个字就试一次登录
const 已试过登录 = new Set();

// 读注册表 文件不存在或坏了返空数组 不抛 让上层走没有源的提示
export async function 读取注册表() {
    const 表 = await 读取文件(源目录, 注册表文件, null);
    return Array.isArray(表) ? 表 : [];
}

// 拿当前该用哪个源 应用设置 源.当前 优先 没有就取注册表第一个
export async function 取当前源标识() {
    const 设置 = (await 读取文件(私有目录.设置, '应用设置', {})) ?? {};
    const 想用 = 设置?.源?.当前;
    const 表 = await 读取注册表();
    if (!表.length) return null;
    if (想用 && 表.some((项) => 项.标识 === 想用)) return 想用;
    return 表[0].标识;
}

// 加载一个源 返 成功 元信息 源 工具 条目 或 失败 阶段 问题
//
// 加载失败不静默 协议 §8 阶段和问题一路带回去 由页面标红显示原因
export async function 加载源(条目) {
    if (!条目?.文件) return { 成功: false, 阶段: '注册表', 问题: [{ 字段: '文件', 行: 0, 问题: '注册表这条没有 `文件` 字段' }] };

    const 代码 = await 读取文本(源目录, 条目.文件, null);
    if (代码 === null || 代码 === '') {
        return { 成功: false, 阶段: '读取', 问题: [{ 字段: '文件', 行: 0, 问题: `读不到源文件「${条目.文件}」` }] };
    }

    // ① 静态提取 不执行源
    const 提取 = 提取元信息(代码);
    if (提取.问题.length) return { 成功: false, 阶段: '提取元信息', 问题: 提取.问题 };

    // ② 校验
    const 校验 = 校验元信息(提取.对象);
    if (!校验.通过) return { 成功: false, 阶段: '校验元信息', 问题: 校验.错误 };

    // ③ 保留标识符 协议 §7 规则 4
    const 保留问题 = 检查保留标识符(代码);
    if (保留问题.length) return { 成功: false, 阶段: '保留标识符', 问题: 保留问题 };

    const 元信息 = 提取.对象;

    // ④ 执行 vite-ignore 不能省 不写 vite 会试图静态分析这个动态 import 构建期就报无法解析
    //    末尾追加 sourceURL 让运行期堆栈带文件名 否则报错只有 blob:xxx
    const 地址 = URL.createObjectURL(
        new Blob([`${代码}\n//# sourceURL=${条目.文件}`], { type: 'text/javascript' })
    );
    try {
        const 模块 = await import(/* @vite-ignore */ 地址);
        if (typeof 模块.default !== 'function') {
            throw new Error('源必须 `export default` 一个函数（协议 §3）');
        }

        const 喵 = 造工具({
            标识: 元信息.标识,
            元信息,
            读取配置: () => (缓存.get(条目.文件)?.条目?.配置 ?? 条目.配置 ?? {}),
            写入配置: async (配置) => {
                // 配置写回由调用方负责 工具只交出新值
                const 会话 = 缓存.get(条目.文件);
                if (会话) 会话.条目.配置 = 配置;
            },
        });

        const 源 = 模块.default(喵);
        if (!源?.标识 || !源?.名称) throw new Error('源对象缺少 `标识` 或 `名称`');

        // ⑤ 能力一致性 元信息声明的必须都真的导出了 协议 §8
        const 缺的 = (元信息.能力 ?? []).filter((名) => typeof 源[名] !== 'function');
        if (缺的.length) throw new Error(`元信息声明了「${缺的.join('、')}」，但源没有导出对应方法`);

        return { 成功: true, 元信息, 源, 工具: 喵, 条目 };
    } catch (错误) {
        return {
            成功: false,
            阶段: '执行源',
            问题: [{ 字段: '源', 行: 0, 问题: String(错误?.message ?? 错误) }],
        };
    } finally {
        URL.revokeObjectURL(地址); // 漏了每次加载都会漏一块内存
    }
}

// 取并缓存当前源 选项.重新加载 可强制重建
export async function 取当前源(选项 = {}) {
    const 标识 = 选项.标识 ?? (await 取当前源标识());
    if (!标识) return { 成功: false, 阶段: '注册表', 问题: [{ 字段: '源', 行: 0, 问题: '还没有任何书源（先去 设置 → 书源 添加）' }] };

    const 条目 = (await 读取注册表()).find((项) => 项.标识 === 标识);
    if (!条目) return { 成功: false, 阶段: '注册表', 问题: [{ 字段: '源', 行: 0, 问题: `注册表里没有「${标识}」` }] };

    if (!选项.重新加载 && 缓存.has(条目.文件)) {
        const 会话 = 缓存.get(条目.文件);
        if (会话.成功) return 会话;
        缓存.delete(条目.文件); // 上次就是坏的 重来一次 用户可能刚改了源文件
    }

    const 结果 = await 加载源(条目);
    结果.条目 = 条目;
    if (结果.成功) 缓存.set(条目.文件, 结果);
    return 结果;
}

// 清掉所有缓存 源文件被改或换当前源时用 详情 目录 封面一起清
export function 清缓存() {
    缓存.clear();
    详情缓存.clear();
    章节缓存.clear();
    封面缓存.clear();
}

// 从 账号.json 里找本源对应的账号并登录
// 找不到账号时明确说清缺什么 不静默失败
export async function 自动登录(会话) {
    const 元信息 = 会话?.元信息 || {};
    if (!元信息.需要登录) return { 成功: true, 跳过: '该源不需要登录' };
    if (typeof 会话.源?.登录至源平台 !== 'function') {
        return { 成功: false, 错误: `「${元信息.名称}」需要登录，但源没有实现 \`登录至源平台\`` };
    }
    const 账号数据 = (await 读取文件(私有目录.用户资源, '账号', {})) ?? {};
    // 认的是 平台id 等于源标识 不是 平台
    // 平台 存的是用户自己给账号起的称呼 随便写 拿来匹配必然找不到
    // 老数据没有 平台id 那时 平台 存的就是源标识 所以回落到它 读取时兜底 不迁移文件
    const 账号 = (账号数据.账号列表 ?? []).find(
        (项) => (项.平台id || 项.平台) === 元信息.标识,
    );
    if (!账号) {
        return {
            成功: false,
            错误: `账号页里没有「${元信息.名称 || 元信息.标识}」的账号 —— 去 设置 → 账号 添加一条，登录的源选「${元信息.名称 || 元信息.标识}」`,
        };
    }
    try {
        const 结果 = await 会话.源.登录至源平台(账号.账号, 账号.密码, {});
        if (结果?.成功) return { 成功: true };
        return { 成功: false, 错误: 结果?.错误 || '登录失败' };
    } catch (错误) {
        return { 成功: false, 错误: String(错误?.message ?? 错误) };
    }
}

// 搜索 返 成功 结果 总页数 或 失败 错误
//
// 登录策略
//   ① 源声明 需要登录 且手上没有 cookie 就先自动登录
//   ② 搜索报需要登录 cookie 过期等 再登录一次并重试一遍
//   ③ 登录失败不硬阻断 很多站 含文库8 实测 需要登录只针对部分功能 匿名就能搜
//      直接返登录失败会白白让一个能用的功能不可用
//      所以先照常搜 真搜不动了才把登录失败原因摆出来
// 两条都走不通就把原因原样抛给页面 不静默失败
export async function 搜索(关键词, 选项 = {}) {
    const 会话 = await 取当前源(选项);
    if (!会话.成功) {
        const 说明 = 会话.问题.map((项) => (项.行 ? `第 ${项.行} 行：${项.问题}` : 项.问题)).join('；');
        return { 成功: false, 错误: `[${会话.阶段}] ${说明}` };
    }
    if (typeof 会话.源.资源搜索 !== 'function') {
        return { 成功: false, 错误: `「${会话.元信息.名称}」没有实现 \`资源搜索\`` };
    }

    let 登录失败原因 = '';
    if (!选项.跳过自动登录 && !选项.已重试) {
        // 工具挂在 会话.工具.工具 上 加载源 存进去的是整个喵对象 版本 工具 日志
        // 源那边就叫 喵.工具.xxx 不是工具本身
        // 漏掉这一层这里永远拿到 undefined 一短路就静默变成没有凭据
        const 饼干 = await 会话.工具?.工具?.Cookie?.获取Cookie?.().catch(() => null);
        const 有凭据 = Array.isArray(饼干) && 饼干.some((条) => 条?.值);
        if (会话.元信息.需要登录 && !有凭据 && !已试过登录.has(会话.元信息.标识)) {
            已试过登录.add(会话.元信息.标识);
            const 登录结果 = await 自动登录(会话);
            if (!登录结果.成功) 登录失败原因 = 登录结果.错误;
            else 已试过登录.delete(会话.元信息.标识); // 成功了就别记着
        }
    }

    try {
        const 结果 = await 会话.源.资源搜索(关键词, 选项);
        return { 成功: true, 结果: 结果?.结果 ?? [], 总页数: 结果?.总页数 ?? 1, 元信息: 会话.元信息 };
    } catch (错误) {
        const 说 = String(错误?.message ?? 错误);
        // 需要登录 是可能自愈的失败 登录一次再试
        if (!选项.已重试 && /登录|login/i.test(说)) {
            已试过登录.delete(会话.元信息.标识); // 允许这次重试真去登录
            const 登录结果 = await 自动登录(会话);
            if (登录结果.成功) return 搜索(关键词, { ...选项, 已重试: true });
            return { 成功: false, 错误: 登录结果.错误 || 说, 需要登录: true };
        }
        // 源自己也会拦需要登录 这时把其实是登录的问题说清楚 别让用户以为源坏了
        const 前缀 = 登录失败原因 ? `登录失败（${登录失败原因}），且 ` : '';
        return { 成功: false, 错误: 前缀 + 说, 需要登录: 登录失败原因 ? true : undefined };
    }
}

// ── 详情 章节列表 封面
//
// 与 搜索 同一套前置 取源 需要登录时自动登录一次 调方法 失败分类
// 差别只在调哪个方法 返回值怎么包 所以抽 备好源 加 调源已备 出来复用
//
// 登录失败不硬阻断 沿用 搜索 的决定
// 先把能拿到的拿到 真拿不到时再把其实是登录的问题摆到错误文案里

// 取源 校验方法存在 需要登录时自动登录一次 返 会话和登录失败原因 或 错误
async function 备好源(方法名, 选项 = {}) {
    const 会话 = await 取当前源(选项);
    if (!会话.成功) {
        const 说明 = 会话.问题.map((项) => (项.行 ? `第 ${项.行} 行：${项.问题}` : 项.问题)).join('；');
        return { 错误: `[${会话.阶段}] ${说明}` };
    }
    if (typeof 会话.源[方法名] !== 'function') {
        return { 错误: `「${会话.元信息.名称}」没有实现 \`${方法名}\`` };
    }
    let 登录失败原因 = '';
    if (!选项.跳过自动登录 && !选项.已重试) {
        // 工具挂在 会话.工具.工具 上 加载源 存进去的是整个喵对象
        // 源那边就叫 喵.工具.xxx 不是工具本身
        // 漏掉这一层这里永远拿到 undefined 一短路就静默变成没有凭据
        const 饼干 = await 会话.工具?.工具?.Cookie?.获取Cookie?.().catch(() => null);
        const 有凭据 = Array.isArray(饼干) && 饼干.some((条) => 条?.值);
        if (会话.元信息.需要登录 && !有凭据 && !已试过登录.has(会话.元信息.标识)) {
            已试过登录.add(会话.元信息.标识);
            const 登录结果 = await 自动登录(会话);
            if (!登录结果.成功) 登录失败原因 = 登录结果.错误;
            else 已试过登录.delete(会话.元信息.标识); // 成功了就别记着
        }
    }
    return { 会话, 登录失败原因 };
}

// ── 详情 目录的进程内缓存
//
// 只按容量淘汰 不设过期 命中就是 0 延迟 不再发请求
// 命中要挪到最新 LRU Map.set 对已存在的键不改顺序 必须先 delete
// 空壳一律不进缓存 详情没有书名 目录是空数组 都不许存
// 否则之后每次打开这本书都命中坏数据 用户还以为这书就是这么烂
//
// 不落盘 源改了简介或书下架之后没有失效手段 存盘只会越看越旧
// 真要做离线书架那是另一件事 要配失效和刷新策略
// 缓存键 源标识 加 书标识 同一本书不同源是两套数据
const 详情缓存 = new Map();
const 章节缓存 = new Map();
const 缓存份数 = 20;

function 读缓存(表, 键) {
    if (!表.has(键)) return null;
    const 值 = 表.get(键);
    表.delete(键); // 先删再塞 等于挪到最新
    表.set(键, 值);
    return 值;
}
function 写缓存(表, 键, 值) {
    表.delete(键);
    表.set(键, 值);
    while (表.size > 缓存份数) 表.delete(表.keys().next().value); // 丢最老的
}
function 缓存键(标识, 源标识) {
    return `${源标识 || ''}::${标识}`;
}

// 调一个取数据类源方法 已经备好源的那一半
//
// 参数 是透传给源的位置参数 不含 选项 源方法最后那个参数一律是 选项 由这里统一补
// 打包 把源返回值收进统一信封
//
// 拆两半是为了让缓存能在备好源之后 真发请求之前插进来 缓存键要用到源标识
async function 调源已备(备, 方法名, 参数, 选项, 打包) {
    const { 会话, 登录失败原因 } = 备;
    try {
        const 结果 = await 会话.源[方法名](...参数, 选项);
        return { 成功: true, ...打包(结果, 会话) };
    } catch (错误) {
        const 说 = String(错误?.message ?? 错误);
        // 需要登录 是可能自愈的失败 登录一次再试
        if (!选项.已重试 && /登录|login/i.test(说)) {
            已试过登录.delete(会话.元信息.标识);
            const 登录结果 = await 自动登录(会话);
            if (登录结果.成功) return 调源已备(备, 方法名, 参数, { ...选项, 已重试: true }, 打包);
            return { 成功: false, 错误: 登录结果.错误 || 说, 需要登录: true };
        }
        const 前缀 = 登录失败原因 ? `登录失败（${登录失败原因}），且 ` : '';
        return { 成功: false, 错误: 前缀 + 说, 需要登录: 登录失败原因 ? true : undefined };
    }
}

// 取一本书的详情 协议 §5 标识 书名 作者 分类 状态 简介 封面 字数 已下架 扩展
// 选项.不复用缓存 可强制重新拉一次 重试刷新用
export async function 获取详情(标识, 选项 = {}) {
    const 备 = await 备好源('获取资源详情', 选项);
    if (备.错误) return { 成功: false, 错误: 备.错误 };
    const 元信息 = 备.会话.元信息;
    const 键 = 缓存键(标识, 元信息.标识);

    const 命中 = 选项.不复用缓存 ? null : 读缓存(详情缓存, 键);
    if (命中) return { 成功: true, 详情: 命中, 元信息, 来自缓存: true };

    const 结果 = await 调源已备(备, '获取资源详情', [标识], 选项, (值) => ({
        详情: 值 && typeof 值 === 'object' ? 值 : null,
    }));
    if (!结果.成功) return 结果;
    // 空壳 连书名都没有 绝不进缓存 那是挑战页或异常页 存下来这本书就永远打不开
    if (结果.详情?.书名 && 结果.详情.书名 !== '未知') 写缓存(详情缓存, 键, 结果.详情);
    return { ...结果, 元信息 };
}

// 取目录 协议 §5 ii 名称 标识 标识是透传令牌 下载时原样传回
// 章节的粒度由源决定 文库8 给的是分卷 它只有分卷打包下载
// 章节 恒为数组
export async function 获取章节列表(标识, 选项 = {}) {
    const 备 = await 备好源('获取目标资源章节列表', 选项);
    if (备.错误) return { 成功: false, 错误: 备.错误 };
    const 元信息 = 备.会话.元信息;
    const 键 = 缓存键(标识, 元信息.标识);

    const 命中 = 选项.不复用缓存 ? null : 读缓存(章节缓存, 键);
    if (命中) return { 成功: true, 章节: 命中, 元信息, 来自缓存: true };

    const 结果 = await 调源已备(备, '获取目标资源章节列表', [标识], 选项, (值) => ({
        章节: Array.isArray(值) ? 值 : [],
    }));
    if (!结果.成功) return 结果;
    // 空目录也不进缓存 可能只是这一次没取到 别把这本书没有目录记死
    if (结果.章节.length) 写缓存(章节缓存, 键, 结果.章节);
    return { ...结果, 元信息 };
}

// 取回封面 协议 §5.1 源只报地址 下载 转码 落盘是工具层的事
// 走源工具里的 取回封面 受 网 权限和 域名集 双重约束
//
// 按地址缓存 详情页每次打开都要挂封面 一本书反复进出就多跑一趟网络
// 封面又几乎不会变 所以取回来的 data URL 直接留一份 只按容量淘汰
const 封面缓存 = new Map();
const 封面缓存份数 = 24;

export async function 取回封面(地址, 选项 = {}) {
    if (!地址) return { 成功: false, 错误: '没有封面地址' };
    const 键 = String(地址);
    if (!选项.不复用缓存) {
        const 命中 = 封面缓存.get(键);
        if (命中) {
            封面缓存.delete(键); // 命中挪最新
            封面缓存.set(键, 命中);
            return { 成功: true, ...命中, 来自缓存: true };
        }
    }
    const 会话 = await 取当前源(选项);
    if (!会话.成功) return { 成功: false, 错误: '书源没加载成功' };
    // 与 备好源 同一个坑 工具在 会话.工具.工具 也就是 喵.工具 不是 会话.工具
    const 工具 = 会话.工具?.工具;
    if (typeof 工具?.取回封面 !== 'function') {
        return { 成功: false, 错误: '本源没有「网」权限，取不了封面' };
    }
    try {
        const 结果 = await 工具.取回封面({ 地址, 请求头: 选项.请求头, 信号: 选项.信号 });
        if (!结果?.地址) return { 成功: false, 错误: '封面下载失败' };
        封面缓存.set(键, 结果);
        while (封面缓存.size > 封面缓存份数) 封面缓存.delete(封面缓存.keys().next().value);
        return { 成功: true, ...结果 };
    } catch (错误) {
        return { 成功: false, 错误: String(错误?.message ?? 错误) };
    }
}
