import { 私有目录, 读取文件, 写入文件, 删除文件, 列出文件, 读取图片, 写入图片 } from './存储';

// 历史记录 属用户资源 落在 数据/用户资源/历史记录.json
//
// 设计约定 用户明确要求 别改
//   所有网络资源信息都从搜索页开始获取 一条记录的起点永远是搜索
//   搜索产生记录后 后续行为升级这条记录 不新增
//   行为只升不降 搜索 到 浏览 到 下载 级别 1 到 2 到 3
//   同一本书再被搜一次 不会把已下载的记录退回搜索
//
// 数据结构 { id, 时间, 行为, 标题, 说明, 源?, 资源标识? }
//   时间 形如 26/10/1 两位年月日 跟初始数据一致
//   id 自增数字字符串 新增时取当前最大值加一
//   说明 先空着 字段留着占位
//   源 和 资源标识 可选 早期数据没有 有它们才能精确认出同一本书
//   没有时退回按标题匹配 别当必填 老数据要能读
//   没有 封面 字段 封面由目录里有没有和 id 同名的图片决定 见文件末尾

const 目录名 = 私有目录.用户资源;
const 文件名 = '历史记录';
// 封面图存放处 文件名主名等于记录 id
// 封面是选了精确结果后从网络下载回来的那本书自己的封面
// 绝不允许共用 也别搞取模循环那套
const 封面目录名 = '历史记录';

// 行为等级 只升不降的判据
export const 行为等级 = { 搜索: 1, 浏览: 2, 下载: 3 };

// 26/10/1 两位数年加月加日 跟着初始数据格式走 别改成 ISO
function 现在() {
    const 今天 = new Date();
    return `${String(今天.getFullYear()).slice(-2)}/${今天.getMonth() + 1}/${今天.getDate()}`;
}

function 解析日期(文本) {
    const [年, 月, 日] = String(文本 || '').split('/').map(Number);
    if (!年 || !月 || !日) return null;
    // 零点 分组比较用大于等于 两边都必须是零点 否则今天 00:00 的记录会被判成昨天
    return new Date(2000 + 年, 月 - 1, 日);
}

// 读全部记录 按 id 从大到小 新的在前 文件不存在或坏了返空数组
export async function 读取全部() {
    const 盘上 = await 读取文件(目录名, 文件名, null);
    if (!Array.isArray(盘上)) return [];
    // id 是字符串数字 排序要按数值比 否则 10 会排在 9 前面
    return [...盘上].sort((甲, 乙) => Number(乙.id) - Number(甲.id));
}

async function 写盘(列表) {
    // 存的时候按 id 从小到大 和初始数据写法一致 读的时候再倒过来
    const 正序 = [...列表].sort((甲, 乙) => Number(甲.id) - Number(乙.id));
    await 写入文件(目录名, 文件名, 正序);
}

// 找同一本书的既有记录
// 优先 源 加 资源标识 精确 没有就退回 标题 老数据里没有那两个字段
function 找同一条(列表, 线索) {
    const 标识 = 线索.资源标识;
    if (线索.源 && 标识) {
        const 命中 = 列表.find((项) => 项.源 === 线索.源 && 项.资源标识 === 标识);
        if (命中) return 命中;
    }
    return 列表.find((项) => 项.标题 === 线索.标题);
}

// 记一次行为 返那条记录
//
// 找不到同一条 新增 这是搜索的正常路径
// 找到且新行为更高级 原地升级
// 找到但等级不升 同级或更低 原样返回 不新增也不回退
export async function 记一次行为(行为 = '搜索', 线索 = {}) {
    const 列表 = await 读取全部();
    const 既有 = 找同一条(列表, 线索);
    if (既有) {
        let 变过 = false;
        if ((行为等级[行为] ?? 0) > (行为等级[既有.行为] ?? 0)) {
            既有.行为 = 行为;
            既有.时间 = 现在();
            变过 = true;
        }
        // 搜索记词 选中后升级为书
        // 搜索产生的是词 标题是用户敲的关键词 用户点开精确结果后
        // 这一条应该就地变成那本书 标题换书名 补源和资源标识 不新增
        // 否则每搜一次点开一本 历史里就多一条重复
        // 标识和源也必须补 不补下次点这条会话就找不到是哪本书
        if (线索.改标题 && 线索.改标题 !== 既有.标题) {
            既有.标题 = 线索.改标题;
            变过 = true;
        }
        if (线索.源 && 既有.源 !== 线索.源) {
            既有.源 = 线索.源;
            变过 = true;
        }
        if (线索.资源标识 && 既有.资源标识 !== 线索.资源标识) {
            既有.资源标识 = 线索.资源标识;
            变过 = true;
        }
        if (变过) await 写盘(列表);
        return 既有;
    }
    const 新记录 = {
        id: String(列表.reduce((最大, 项) => Math.max(最大, Number(项.id) || 0), 0) + 1),
        时间: 现在(),
        行为,
        标题: 线索.标题 ?? '',
        说明: '', // 先空着 这个字段暂时没用上 留个位置
    };
    // 有才写 老数据里没这两个字段 别给每条新记录都塞空串
    if (线索.源) 新记录.源 = 线索.源;
    if (线索.资源标识) 新记录.资源标识 = 线索.资源标识;
    列表.unshift(新记录);
    await 写盘(列表);
    return 新记录;
}

// 删一条 连它的封面文件一起删
// 否则 历史记录 目录里会积一堆没人引用的图 而它们按 id 加后缀命名 将来 id 复用还会张冠李戴
export async function 删除记录(id) {
    await 删封面(await 取封面名录(), id);
    await 写盘((await 读取全部()).filter((项) => String(项.id) !== String(id)));
}

// 清空
export async function 清空历史() {
    const 名录 = await 取封面名录();
    for (const id of 名录.keys()) await 删封面(名录, id);
    await 写盘([]);
}

// ───────── 分组 给搜索页渲染用
//
// 五档 今天 昨天 一周内 一个月内 更早之前 互不重叠
//   今天 只显示 今天 两个字
//   后四档要在标题里带组内第一条的时间 那是这组里最新的那条
//     例 昨天 | 9.30 一周内 | 9.28 一个月内 | 9.5 更早之前 | 8.1
//   时间本年抹掉年份 26/10/1 到 10/1 跨年的才显示完整 25/12/30
export async function 读取分组() {
    const 列表 = await 读取全部();
    // 只扫这一次目录 下面每条从表里查 别在循环里反复列目录 一次 IPC 一帧
    const 封面名录 = await 取封面名录();

    const 今 = new Date();
    今.setHours(0, 0, 0, 0);
    const 昨 = new Date(今); 昨.setDate(今.getDate() - 1);
    const 七日前 = new Date(今); 七日前.setDate(今.getDate() - 7);
    const 三十日前 = new Date(今); 三十日前.setDate(今.getDate() - 30);

    // 档位判定 用日期比较不用天数差 用户看的是哪一天 不是过了多少小时
    function 定档(日) {
        if (!日) return '更早之前';
        if (日 >= 今) return '今天';
        if (日 >= 昨) return '昨天';
        // 一周内 等于 前天到 7 天前 昨 已经吃掉昨天了
        if (日 >= 七日前) return '一周内';
        if (日 >= 三十日前) return '一个月内';
        return '更早之前';
    }

    const 分组表 = new Map(); // 档名 到 时间 收回 会话列表
    for (const 项 of 列表) {
        const 日 = 解析日期(项.时间);
        const 档 = 定档(日);
        if (!分组表.has(档)) 分组表.set(档, { 档, 收回: 档 !== '今天', 会话列表: [] });
        分组表.get(档).会话列表.push({
            ...项,
            // 会话行显示的时间也抹过年份 用户要求时间都抹除本年显示
            // 原始时间只留在盘上 渲染层不该拿到会让人困惑的完整年份
            时间: 短时间(项.时间),
            说明: 项.说明 || '',
            // 允许没有封面 只搜索过还没选精确结果的记录本来就没有
            // 返回空串 页面走默认底色 不占位不留白框
            封面地址: 读封面(封面名录, 项.id),
        });
    }

    // 固定按五档顺序输出 Map 的插入顺序会让更早之前跑到前面去
    const 顺序 = ['今天', '昨天', '一周内', '一个月内', '更早之前'];
    return 顺序
        .filter((档) => 分组表.has(档))
        .map((档) => {
            const 组 = 分组表.get(档);
            // 组内第一条就是最新那条 读取全部 已经按 id 倒序 它的时间就是组标题那个
            const 首条时间 = 组.会话列表[0]?.时间;
            return {
                ...组,
                时间: 档 === '今天' ? '今天' : `${档} | ${短时间(首条时间)}`,
            };
        });
}

// 26/10/1 到本年 10/1 往年 25/12/30
// 抹除本年 是用户的要求 今年的事不用年年重复提醒 跨年才需要标出来
function 短时间(文本) {
    const [年, 月, 日] = String(文本 || '').split('/');
    if (!年 || !月 || !日) return 文本 || '';
    const 今年 = String(new Date().getFullYear()).slice(-2);
    return 年 === 今年 ? `${月}/${日}` : `${年}/${月}/${日}`;
}

// ───────── 封面
//
// 封面是那本书自己的封面 在这条记录选了精确结果之后从网络下载落盘到
// 数据/用户资源/历史记录/id.后缀
//
// 判据就是目录里有没有和 id 同名的图片 记录里不存封面字段
// 少一个字段就少一处会对不上的地方 改名 删文件 换后缀都不会留下脏数据
//
// 一条记录一个文件 不许共用 也不做按 id 取模 那是错的 不同书会用同一张图
// 允许没有 搜过但还没选精确结果的记录就是没有 返回空串即可

// 扫一次封面目录 建 id 到文件名的表 主名就是 id 后缀随意
// 列出文件 认的是相对私有空间根 的完整路径 数据/用户资源/历史记录
// 少一层前缀它不会报错 只会安静地返回空数组
async function 取封面名录() {
    const 表 = new Map();
    try {
        for (const 名 of await 列出文件(`${目录名}/${封面目录名}`)) {
            const 点 = 名.lastIndexOf('.');
            if (点 <= 0) continue; // 无扩展名的跳过
            const 后缀 = 名.slice(点 + 1).toLowerCase();
            if (!/^(png|jpe?g|gif|webp|bmp)$/.test(后缀)) continue; // 只认图片
            表.set(名.slice(0, 点), 名);
        }
    } catch {
        // 目录还不存在 一条封面都没有 是常态 空表即可
    }
    return 表;
}

// 读一张封面 到 能直接喂给 img 的 data URL 没有或读失败返空串
function 读封面(名录, id) {
    const 名 = 名录.get(String(id));
    if (!名) return '';
    const 数据 = 读取图片(`${目录名}/${封面目录名}/${名}`);
    if (!数据) return '';
    const 后缀 = (名.split('.').pop() || 'png').toLowerCase();
    return `data:image/${后缀 === 'jpg' ? 'jpeg' : 后缀};base64,${数据}`;
}

// 删掉某条 id 的封面文件 删完顺手从表里移除 调用方可能连着删多条
// 只删这一个 id 的 别人的封面不许动
async function 删封面(名录, id) {
    const 名 = 名录.get(String(id));
    if (!名) return;
    await 删除文件(`${目录名}/${封面目录名}`, 名);
    名录.delete(String(id));
}

// 给某条记录落一张封面 只写文件 id 加后缀 不碰记录 记录里本来就没这个字段
// base64数据 是纯 base64 不带 data 前缀 返是否成功 失败就当这条没有封面
//
// 后缀变了要把旧文件删掉 否则 1.jpg 和 1.png 会同时躺在目录里 按 id 找的规则没规定用哪个
export async function 设置封面(id, base64数据, 后缀 = 'jpg') {
    if (!id || !base64数据) return false;
    const 干净后缀 = String(后缀).toLowerCase().replace('jpeg', 'jpg');
    const 名录 = await 取封面名录();
    const 旧名 = 名录.get(String(id));
    if (旧名 && 旧名 !== `${id}.${干净后缀}`) await 删封面(名录, id);
    return 写入图片(`${目录名}/${封面目录名}/${id}.${干净后缀}`, base64数据).成功;
}
