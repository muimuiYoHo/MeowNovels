// 越界拉伸回弹 边界继续拖就把内容拉伸 松手弹回
//
// 铁律 单次手势锁死拉伸方向 手指反向只让量归零 绝不反向拉伸
// 反向拉伸要补偿位移跨 0 翻转 那条路一直有换向首帧掉帧 查不出根因 锁方向就绕开了
//
// 用 scale 不用 translate 平移要露白 每帧重绘整层 scale 只动合成矩阵
// 安卓 12+ 的 EdgeEffect 本身就是拉伸内容 不是自创效果
// 拉伸时副轴轻微压窄 保持体积感
//
// 曲线 拉伸率 = A*x/(x+S) 渐近不钳位 撞墙感来自 Math.min 触顶后彻底没响应
// 横向纵向各一个开关 纵向要接管滚动盒 横向不碰 合成一个开关就会一关全关
// 纵向现在关着 换向首帧掉帧没定位前先停 停了就把滚动盒整段交还浏览器

const 启用纵向拉伸 = false;
const 启用横向拉伸 = true;

const 拉伸起始位移 = 6; // 超过它才开始拉伸 轻触不抖
const 拉伸渐近比例 = .16; // 曲线的渐近高度 永远达不到
const 拉伸饱和尺度 = 900; // 越小越早接近渐近高度 越拉越沉
const 横向补偿比例 = .35; // 主轴放大时副轴压窄多少

// 超出位移 到 拉伸比例 纯曲线 无钳位 无边界
function 计算拉伸量(超出位移) {
    if (超出位移 <= 0) return 0;
    // 等效线性斜率 = 渐近比例 / 饱和尺度 100px 约拉 1.8% 起步轻快 长拉变沉
    return (拉伸渐近比例 * 超出位移) / (超出位移 + 拉伸饱和尺度);
}

// 由 拉伸量 和 方向 拼 transform
//
// 四个方向独立 各自恒 >= 0 照 AOSP 建模 EdgeEffect 有四个实例 没有带符号拉伸
// 不用 transform-origin 钉边 改它会让合成层重新栅格化 每换一次方向首帧必掉帧
// 以 center 为原点加一个平移 数学上等价于以某条边为原点缩放
//   钉顶边向下伸展 位移 +n*h/2 钉底边 -n*h/2 左右同理
// 恒输出 translate3d 加 scale3d 结构恒定 值变时不会重建合成层
function 拼接变换字符串(拉伸量, 方向, 页面尺寸) {
    const 有效拉伸量 = 拉伸量 || 0;
    const 主轴缩放 = 1 + 有效拉伸量; // 拉伸轴恒放大
    const 副轴缩放 = 1 - 有效拉伸量 * 横向补偿比例; // 副轴轻压 保持体积感
    const 是纵向 = 方向 !== "右拉" && 方向 !== "左拉";

    // 补偿位移 = (s-1) * 半轴长度 符号看钉哪条边
    const 半轴长度 = 是纵向
        ? 页面尺寸 && 页面尺寸.高
            ? 页面尺寸.高 / 2
            : 0
        : 页面尺寸 && 页面尺寸.宽
          ? 页面尺寸.宽 / 2
          : 0;
    const 补偿距离 = 有效拉伸量 * 半轴长度; // s-1 = 拉伸量
    let 补偿位移x = 0;
    let 补偿位移y = 0;
    if (方向 === "下拉") 补偿位移y = 补偿距离;
    else if (方向 === "上拉") 补偿位移y = -补偿距离;
    else if (方向 === "右拉") 补偿位移x = 补偿距离;
    else if (方向 === "左拉") 补偿位移x = -补偿距离;

    const 缩放片段 = 是纵向
        ? "scale3d(" + 副轴缩放 + ", " + 主轴缩放 + ", 1)"
        : "scale3d(" + 主轴缩放 + ", " + 副轴缩放 + ", 1)";
    return "translate3d(" + 补偿位移x + "px, " + 补偿位移y + "px, 0) " + 缩放片段;
}

// 四个量各自独立 恒 >= 0 同一时刻至多一个非零
// 跟手中 控制过渡开关 按着时 none 保证 1:1 跟手
export function 初始拉伸状态() {
    return {
        下拉量: 0, // 贴顶继续下拉 钉顶边 内容向下伸展
        上拉量: 0, // 到底继续上拉 钉底边 内容向上伸展
        右拉量: 0, // 首页继续右拉 钉左边 内容向右伸展
        左拉量: 0, // 末页继续左拉 钉右边 内容向左伸展
        跟手中: false,
    };
}

// 只改传入的状态和当前页 DOM 不依赖 Vue
// 变量名一律写完整词组 单字名在这个文件里极易看错
export function 创建拉伸回弹({ 视口宽, 视口高, 取页元素, 取滚动盒, 状态 }) {
    if (!状态) throw new Error("创建拉伸回弹：必须传入状态对象");

    // 跟手期间已直写进 DOM 的拉伸值
    // 走 reactive 每个 rAF 都要重渲染三页 :style 每帧 9 次样式写入 120Hz 下就是掉帧
    // 直写 transform 绕开渲染管线 代价是 vdom 和 DOM 脱节 松手必须回填
    let 视觉拉伸量 = 0;
    let 视觉拉伸方向 = "";

    // 本次手势锁的方向 空串表示未锁 锁上就不改
    let 已锁定拉伸方向 = "";

    function 取视口宽() {
        return (typeof 视口宽 === "function" ? 视口宽() : 视口宽) || 360;
    }
    function 取视口高() {
        return (typeof 视口高 === "function" ? 视口高() : 视口高) || 0;
    }
    // 页面尺寸完全不读 DOM
    // .页 恒视口等大 宽高直接由视口推 读 clientWidth 会强制同步布局 正好落在跟手首帧
    function 取页面尺寸() {
        return { 宽: 取视口宽(), 高: 取视口高() };
    }

    // 页元素引用缓存 跟手直写和回弹 readback 都要用
    let 页元素缓存 = {};
    function 取当前页元素() {
        const 当前页索引 = 状态.当前页;
        if (Object.prototype.hasOwnProperty.call(页元素缓存, 当前页索引)) {
            return 页元素缓存[当前页索引];
        }
        const 页元素 = 取页元素 ? 取页元素(当前页索引) : null;
        页元素缓存[当前页索引] = 页元素;
        return 页元素;
    }

    // 滚动盒和滚动上限缓存 布局属性每帧重复读会强制同步布局 只在手势开始固定一次
    let 滚动盒缓存索引 = -1;
    let 滚动盒缓存元素 = null;
    let 滚动上限缓存 = null;
    function 取滚动盒元素() {
        const 当前页索引 = 状态.当前页;
        if (当前页索引 !== 滚动盒缓存索引 || !滚动盒缓存元素) {
            滚动盒缓存元素 = 取滚动盒 ? 取滚动盒(当前页索引) : null;
            滚动盒缓存索引 = 当前页索引;
            滚动上限缓存 = null;
        }
        return 滚动盒缓存元素;
    }
    function 是否贴顶() {
        const 滚动盒 = 取滚动盒元素();
        return !滚动盒 || 滚动盒.scrollTop <= 0;
    }
    function 是否贴底() {
        const 滚动盒 = 取滚动盒元素();
        if (!滚动盒) return true; // 内容不足一屏 视为同时贴顶贴底
        if (滚动上限缓存 === null) {
            滚动上限缓存 = Math.max(0, 滚动盒.scrollHeight - 滚动盒.clientHeight);
        }
        return 滚动盒.scrollTop >= 滚动上限缓存 - 1;
    }

    // 写入一次拉伸 记视觉值 直写当前页 transform 不走 Vue
    function 写入拉伸(拉伸量, 方向) {
        视觉拉伸量 = 拉伸量;
        视觉拉伸方向 = 方向;
        const 页元素 = 取当前页元素();
        if (页元素) 页元素.style.transform = 拼接变换字符串(拉伸量, 方向, 取页面尺寸());
    }

    // 复位一次拉伸 手势开始 取消 切页都用
    function 复位拉伸() {
        视觉拉伸量 = 0;
        视觉拉伸方向 = "";
        已锁定拉伸方向 = "";
        const 页元素 = 取当前页元素();
        if (页元素) 页元素.style.transform = 拼接变换字符串(0, "", 取页面尺寸());
    }

    // 手势开始 解锁方向 复位视觉值和 DOM 接管滚动边界
    function 手势开始() {
        页元素缓存 = {}; // 期间可能布局变了 元素引用重取
        状态.跟手中 = true; // 按下瞬间就关过渡 保证 1:1 跟手

        // 立刻直写 DOM 复位 不等 Vue 渲染
        // 只靠 reactive 清零不行 松手回填和新手势清零可能落进同一批 microtask 净变化 0
        // Vue 判定无更新 DOM 就停在旧拉伸上
        复位拉伸();

        // 以下整段只为纵向拉伸服务 纵向关掉必须整段跳过
        // 这段会把滚动盒 overscroll-behavior 改成 none 且没有恢复逻辑 执行一次就永久
        // 纵向不接管滚动了 再改只会破坏原生滚动
        if (!启用纵向拉伸) return;

        滚动盒缓存索引 = -1; // 滚动盒引用重新解析

        // 不能让 WebView 同时启动它自己的 EdgeEffect 原生过度回弹一旦启动就在整个触摸序列里参与合成
        const 滚动盒 = 取滚动盒元素();
        if (滚动盒) {
            滚动盒.style.overscrollBehavior = "none";
            滚动盒.style.overscrollBehaviorY = "none";
            滚动上限缓存 = Math.max(0, 滚动盒.scrollHeight - 滚动盒.clientHeight);
        }
    }

    // 纵向移动 返 true 表示已接管 返 false 交还浏览器滚动
    // 未锁 只在贴顶下拉 或 贴底上拉 且超起始位移时锁
    // 已锁 只按锁定方向取投影 反向时投影变小 量连续减到 0 后停住
    // 是否贴顶 是否贴底 只在锁定那一刻判一次 不然反向会让量瞬间归零 画面弹一下
    function 处理纵向拉伸(纵向位移) {
        // 关掉时返 false 纵向完全归浏览器
        if (!启用纵向拉伸) return false;
        if (!已锁定拉伸方向) {
            if (纵向位移 > 拉伸起始位移 && 是否贴顶()) 已锁定拉伸方向 = "下拉";
            else if (纵向位移 < -拉伸起始位移 && 是否贴底()) 已锁定拉伸方向 = "上拉";
            if (!已锁定拉伸方向) return false;
        }
        // 投影 位移在锁定方向上的分量 反向移动时变小乃至变负
        const 沿锁定方向投影 = 已锁定拉伸方向 === "下拉" ? 纵向位移 : -纵向位移;
        写入拉伸(计算拉伸量(沿锁定方向投影 - 拉伸起始位移), 已锁定拉伸方向);
        return true;
    }

    // 横向越界 首页右拉 末页左拉 返 true 表示接管
    // 首页末页由调用方判 只有滑动模块知道页数和当前页
    // 锁定规则同纵向 量归零后返 false 交还横向跟手
    function 处理横向越界拉伸(横向位移, 是首页, 是末页) {
        // 关掉时返 true 不是 false
        // true 的语义是已接管 调用方不许再跟手平移
        // 返 false 会让轨道真移出边界 露出空白 比拉伸还难看
        if (!启用横向拉伸) return true;
        if (!已锁定拉伸方向) {
            if (是首页 && 横向位移 > 拉伸起始位移) 已锁定拉伸方向 = "右拉";
            else if (是末页 && 横向位移 < -拉伸起始位移) 已锁定拉伸方向 = "左拉";
            if (!已锁定拉伸方向) return false;
        }
        const 沿锁定方向投影 = 已锁定拉伸方向 === "右拉" ? 横向位移 : -横向位移;
        const 拉伸量 = 计算拉伸量(沿锁定方向投影 - 拉伸起始位移);
        if (拉伸量 <= 0) {
            写入拉伸(0, 已锁定拉伸方向); // 输出单位变换 保持结构恒定
            return false;
        }
        写入拉伸(拉伸量, 已锁定拉伸方向);
        return true;
    }

    // 松手结算 把直写的拉伸值回填进 reactive 再让过渡接管
    // 不能同帧清零 清量会把 transform 瞬间设成单位 过渡起点没被记录
    // Vue 是异步批量刷新 切过渡和清量落进同一次刷新 浏览器只能从随手抓到的当前值起播
    // 四步 回填 等一帧 切过渡 readback 再一帧归零
    // 归零用代号不用单个 rAF 句柄 单句柄拦不住已排上的第二个 竞态
    let 归零代号 = 0;
    function 作废归零回调() {
        归零代号++; // 让所有在途回调失效
    }
    function 松手归位() {
        状态.下拉量 = 视觉拉伸方向 === "下拉" ? 视觉拉伸量 : 0;
        状态.上拉量 = 视觉拉伸方向 === "上拉" ? 视觉拉伸量 : 0;
        状态.右拉量 = 视觉拉伸方向 === "右拉" ? 视觉拉伸量 : 0;
        状态.左拉量 = 视觉拉伸方向 === "左拉" ? 视觉拉伸量 : 0;
        视觉拉伸量 = 0;
        视觉拉伸方向 = "";
        已锁定拉伸方向 = ""; // 松手即解锁 下次手势重新判方向

        const 本次代号 = ++归零代号;
        // ② 等一帧 让回填上屏 此时 transition 还是 none 画面不动
        requestAnimationFrame(() => {
            if (本次代号 !== 归零代号) return; // 已被新手势或新松手作废
            状态.跟手中 = false; // ③ 切过渡 值不动 起点被记录
            requestAnimationFrame(() => {
                if (本次代号 !== 归零代号) return;
                const 页元素 = 取当前页元素();
                // ④ readback 把新 transition 和当前 transform 钉成起点
                if (页元素) void 页元素.offsetHeight;
                requestAnimationFrame(() => {
                    if (本次代号 !== 归零代号) return;
                    状态.下拉量 = 0;
                    状态.上拉量 = 0;
                    状态.右拉量 = 0;
                    状态.左拉量 = 0;
                    // 量归零 方向由哪个量非零决定 不用保留方向到动画播完
                });
            });
        });
    }

    // 每页容器样式
    // 非当前页也返单位变换 不返 null null 会让 transform 从 scale3d 消失成 none 硬跳变
    // 属性常驻 过渡两端才可比
    // 必须纯读 不在渲染期写状态
    function 页面样式(页索引) {
        const 是当前页 = 页索引 === 状态.当前页;
        let 当前拉伸量 = 0;
        let 当前方向 = "下拉";
        if (是当前页) {
            // 跟手期间拉伸值是直写 DOM 的 reactive 里还是 0 这里必须优先读视觉值
            // 否则任何一次重渲染都会把 DOM 盖回单位变换
            if (视觉拉伸量) {
                当前拉伸量 = 视觉拉伸量;
                当前方向 = 视觉拉伸方向 || "下拉";
            } else if (状态.下拉量) {
                当前拉伸量 = 状态.下拉量;
                当前方向 = "下拉";
            } else if (状态.上拉量) {
                当前拉伸量 = 状态.上拉量;
                当前方向 = "上拉";
            } else if (状态.右拉量) {
                当前拉伸量 = 状态.右拉量;
                当前方向 = "右拉";
            } else if (状态.左拉量) {
                当前拉伸量 = 状态.左拉量;
                当前方向 = "左拉";
            }
        }
        return {
            // transform 必须常驻 全是 1 也要有 不然松手属性被移除 过渡没了起止两端 回弹变瞬跳
            transform: 拼接变换字符串(当前拉伸量, 当前方向, 取页面尺寸()),
            transition: 状态.跟手中 ? "none" : "transform 0.34s cubic-bezier(0.22, 0.61, 0.36, 1)",
            // 不输出 transformOrigin .页 本来就是 center center 每帧少写一个键
        };
    }

    // 视口变化 旋转 键盘 切页 时作废缓存引用 尺寸每次从视口现取不用清
    function 作废尺寸缓存() {
        滚动盒缓存索引 = -1;
        滚动上限缓存 = null;
        页元素缓存 = {};
    }

    return {
        手势开始,
        处理纵向拉伸,
        处理横向越界拉伸,
        松手归位,
        作废归零回调,
        页面样式,
        作废尺寸缓存,
    };
}
