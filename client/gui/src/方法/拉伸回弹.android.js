// 越界拉伸回弹：边界处继续拖动时把内容「拉伸」（scale），松手后弹回原位。
//
// ── 为什么从 滑动翻页.android.js 分离出来 ──
// 两者关注点完全不同：滑动翻页管「横向翻页的判定与轨道平移」，
// 这里管「纵向越界拉伸 / 横向首末页越界拉伸 / 松手回弹」。
// 混在一个文件里已经踩过坑：局部 `方向` 遮蔽了外层的手势方向、`拉伸量` 与 `量`
// 混用、`方` 未声明 —— 非严格模式下不报错，只是静默失效或抛异常。
// 分离后本模块**自包含**：曲线、方向锁定、滚动盒判定、transform 拼装、回弹时序。
//
// ── 【铁律】单次手势内锁定拉伸方向，绝不中途改变 ──
// 一旦本次手势锁定了某个拉伸方向（下拉 / 上拉 / 右拉 / 左拉），本次手势内就**只按
// 该方向取投影**：手指反向只会让投影变小、拉伸量归零，**不会**变成反方向的拉伸。
//
// 为什么定这条铁律：反向拉伸意味着补偿位移跨 0 翻转（ty 从 +N 变 −N）。
// 那条路径在真机上一直有个「换向首帧掉帧」的问题 —— 主线程、cc 栅格化、
// SurfaceFlinger 三层测量全部正常，但用户手感明确（项目笔记的搁置 #1）。
// 锁方向后这条路径**根本不存在**，只剩「量归零 → 松手 → 新手势」，
// 而松手归位是实测平滑的。用行为约束换掉一个查不出根因的性能问题，划算。
//
// ── 为什么用 scale 拉伸而不是 translate 位移 ──
// 1. 平移要露出容器外的空白、每帧重绘整层；scale 只影响合成层的绘制矩阵
// 2. 原生 Android 12+ 的 EdgeEffect 就是拉伸内容本身（渲染管线级 stretch）、无背景跟随，
//    所以 scale 才是有依据的还原，不是自创效果
// 3. 拉伸时同步轻微压窄另一轴，保持视觉体积感（原生也这么做）
// 4. 拉伸率走渐进曲线、不设硬上限：拉到底也一直在响应，而不是撞墙（见 计算拉伸量）

// ── 曲线参数（对齐原生 StretchEdgeEffect 的手感）──
//
// 拉伸率是「渐进曲线」而不是「线性 + 硬上限」：
// 早期用 Math.min(上限, ...) 会在触顶那一刻彻底失去响应 —— 手指还在动、画面却死了，
// 手感像撞墙。改成有理衰减式 f(x) = A·x/(x+S)：
//   · x→0 时斜率 = A/S，近似线性（轻微触摸有即时反馈）
//   · x→∞ 时渐近到 A，永远不达、也永远不硬停 —— 一直有微弱响应
//   · 单调递增、全程可导，没有折点
// 于是「上限」不再是钳位值，而是参数 A（曲线的渐近高度），S 是「多快接近 A」。
// ── 两个方向独立开关（横向 / 纵向解耦）──
//
// 为什么必须解耦：横向越界拉伸（首末页钉边拉伸）和纵向越界拉伸（贴顶/贴底拉伸）
// 走的是同一条投影+锁定逻辑，但**触发条件与副作用完全不同** ——
// 纵向要接管滚动边界（改滚动盒样式），横向不碰滚动盒。
// 用一个总开关会让「只想停纵向」变成「横向也没了」。
//
// 纵向：**暂时关掉**。搁置 #1（换向首帧掉帧）根因未定位前先停用。
//       关掉后纵向越界不接管 → 完全交还浏览器做原生滚动；同时 手势开始 里那段
//       「接管滚动边界」的准备也会整段跳过（不跳会反过来破坏原生滚动，见那儿的说明）。
// 横向：**保留**。它不依赖滚动盒，与纵向互不影响。
//
// 恢复纵向时改回 true 即可 —— 调用点一个都不用动，这也正是它做成常量的理由。
const 启用纵向拉伸 = false;
const 启用横向拉伸 = true;

const 拉伸起始位移 = 6; // 位移超过它才开始拉伸，避免轻触就抖
const 拉伸渐近比例 = .16; // 拉伸率的渐近高度：曲线无限趋近但永远达不到
const 拉伸饱和尺度 = 900; // 饱和尺度 S：越小越早接近渐近高度（越拉越沉的手感）
const 横向补偿比例 = .35; // 拉伸轴放大时，另一轴压窄的比例系数

// 超出位移 → 拉伸比例：[0, 拉伸渐近比例)，纯曲线、无钳位、无边界
function 计算拉伸量(超出位移) {
    if (超出位移 <= 0) return 0;
    // 等效线性区斜率 = 拉伸渐近比例 / 拉伸饱和尺度（≈ 0.000178 /px），
    // 即 100px 位移约拉 1.8%，起步轻快、长拉迅速变沉。
    return (拉伸渐近比例 * 超出位移) / (超出位移 + 拉伸饱和尺度);
}

// 由「拉伸量（非负） + 方向」拼出完整的 transform 字符串。
//
// 【为什么是「四个方向」而不是「一个带符号标量」】（对齐 AOSP）
// 原生 `EdgeEffect` 是**四个独立实例**（top/bottom/left/right），每个的 `mDistance`
// 都是 0..1、**恒 >= 0**，方向由「哪个实例」隐含 —— 没有「带符号拉伸」这个概念。
// 我们照此建模：`下拉量/上拉量/右拉量/左拉量` 各自独立、恒 >= 0，
// 「钉哪条边」由「哪个量非零」决定，不需要「方向记忆位 + 延迟复位」那套机制。
//
// 【为什么不用 transform-origin 钉边，改用 translate 补偿】
// 旧做法是让 transform-origin 跟着方向变（下拉 center top / 上拉 center bottom …）。
// 但 transform-origin 是**瞬时**属性、且改它会让合成层内容重新栅格化 ——
// 实测表现就是「每换一次方向的第一帧必掉一次帧」（同方向反复拉不卡）。
//
// 数学上二者等价：以 center 为原点、配合一个平移，可完全复现「以某条边为原点」的缩放。
//   origin=top    + scaleY(s) ≡ origin=center + translateY(+(s-1)·h/2) + scaleY(s)
//   origin=bottom + scaleY(s) ≡ origin=center + translateY(-(s-1)·h/2) + scaleY(s)
//   origin=left   + scaleX(s) ≡ origin=center + translateX(+(s-1)·w/2) + scaleX(s)
//   origin=right  + scaleX(s) ≡ origin=center + translateX(-(s-1)·w/2) + scaleX(s)
// （已用脚本对 h=853、s=1.05/0.95 逐点验证一致）
//
// 于是 transform-origin 可以**永远保持 center center 不变**，合成层不再重建。
//
// 四个方向**一律放大**（s = 1 + 拉伸量），区别只在「钉住哪条边」，即补偿位移朝哪一侧：
//   "下拉" → 钉顶边，元素向下伸展（位移 +n·h/2）
//   "上拉" → 钉底边，元素向上伸展（位移 -n·h/2）
//   "右拉" → 钉左边，元素向右伸展（位移 +n·w/2）
//   "左拉" → 钉右边，元素向左伸展（位移 -n·w/2）
//
// 恒输出「translate3d + scale3d」两段结构（量为 0 时是 translate3d(0px,0px,0) scale3d(1,1,1)）：
// 结构恒定才能保证 transform 值变化时只有数值在动，不触发合成层按结构重建。
function 拼接变换字符串(拉伸量, 方向, 页面尺寸) {
    const 有效拉伸量 = 拉伸量 || 0;
    const 主轴缩放 = 1 + 有效拉伸量; // 拉伸轴恒放大
    const 副轴缩放 = 1 - 有效拉伸量 * 横向补偿比例; // 另一轴轻微压窄，保持体积感
    const 是纵向 = 方向 !== "右拉" && 方向 !== "左拉";

    // 补偿位移 = (s-1)·半轴长度，符号由「钉哪条边」决定
    const 半轴长度 = 是纵向
        ? 页面尺寸 && 页面尺寸.高
            ? 页面尺寸.高 / 2
            : 0
        : 页面尺寸 && 页面尺寸.宽
          ? 页面尺寸.宽 / 2
          : 0;
    const 补偿距离 = 有效拉伸量 * 半轴长度; // s-1 = 拉伸量
    let 补偿位移x = 0;
    let 补偿位移y = 0;
    if (方向 === "下拉") 补偿位移y = 补偿距离;
    else if (方向 === "上拉") 补偿位移y = -补偿距离;
    else if (方向 === "右拉") 补偿位移x = 补偿距离;
    else if (方向 === "左拉") 补偿位移x = -补偿距离;

    const 缩放片段 = 是纵向
        ? "scale3d(" + 副轴缩放 + ", " + 主轴缩放 + ", 1)"
        : "scale3d(" + 主轴缩放 + ", " + 副轴缩放 + ", 1)";
    return "translate3d(" + 补偿位移x + "px, " + 补偿位移y + "px, 0) " + 缩放片段;
}

// 拉伸相关的状态字段。由 滑动翻页.初始状态() 合并进去 ——
// 组件仍然只建一个 reactive 对象，对外形状不变。
//
// 四个量各自独立、恒 >= 0；同一时刻至多一个非零。
// `跟手中` 控制过渡开关（按着时 none 保证 1:1 跟手），也由本模块维护。
export function 初始拉伸状态() {
    return {
        下拉量: 0, // 贴顶继续下拉 → 钉顶边，内容向下伸展
        上拉量: 0, // 到底继续上拉 → 钉底边，内容向上伸展
        右拉量: 0, // 首页继续右拉 → 钉左边，内容向右伸展
        左拉量: 0, // 末页继续左拉 → 钉右边，内容向左伸展
        跟手中: false,
    };
}

// 创建一套拉伸回弹逻辑。
// 方法只改传入的状态对象与「当前页」的 DOM，不依赖 Vue。
//
// ⚠️ 变量名一律写成完整词组（不用 量 / 方 / 盒 / 首 这类单字）：
// 本模块的状态位较多（四个拉伸量 + 方向锁 + 视觉值 + 滚动盒缓存），
// 单字名在这个文件里极易看错，之前就因为 `量` 与 `拉伸量` 混用出过静默 bug。
export function 创建拉伸回弹({ 视口宽, 视口高, 取页元素, 取滚动盒, 状态 }) {
    if (!状态) throw new Error("创建拉伸回弹：必须传入状态对象");

    // 「跟手期间已直写进 DOM 的拉伸值」。
    //
    // 纵向拉伸是每帧都在变的属性。走 reactive 就意味着每个 rAF 都要重渲染三页的
    // :style（Vue 的 patchStyle 会把对象里每个键都往 el.style 上写一遍，3 页 × 3 键
    // = 每帧 9 次样式写入）。在 120Hz 下这段开销正好落在「拉到期间」，
    // 实测表现就是拉伸过程掉帧（而松手回弹平滑，因为那时已经没有高频写入了）。
    // 所以跟手期间**直接写当前页的 transform**，绕开渲染管线；
    // 代价是 vdom 与 DOM 脱节，必须在松手时把视觉值回填进 reactive（见 松手归位 ①）。
    let 视觉拉伸量 = 0;
    let 视觉拉伸方向 = "";

    // 本次手势锁定的拉伸方向（"" = 未锁定）。锁上之后本手势内**绝不改变** —— 见模块头部铁律。
    let 已锁定拉伸方向 = "";

    function 取视口宽() {
        return (typeof 视口宽 === "function" ? 视口宽() : 视口宽) || 360;
    }
    function 取视口高() {
        return (typeof 视口高 === "function" ? 视口高() : 视口高) || 0;
    }
    // ── 页面尺寸：**完全不读 DOM** ──
    //
    // .页 恒为「视口等大」：轨道宽 = 3× 视口，每页 width = calc(100%/3) = 视口宽；
    // 高度 100%（轨道高 = 内容区高 = 视口高，导航栏是悬浮胶囊、不占布局）。
    // 所以宽高直接由视口推得，没必要读 clientWidth/clientHeight ——
    // 而那个读取会触发**强制同步布局**，且恰好落在「跟手首帧 / 换向后首帧」
    // 这个最敏感的位置。
    function 取页面尺寸() {
        return { 宽: 取视口宽(), 高: 取视口高() };
    }

    // 页元素引用缓存（跟手直写 DOM 与回弹前 readback 都要用）
    let 页元素缓存 = {};
    function 取当前页元素() {
        const 当前页索引 = 状态.当前页;
        if (Object.prototype.hasOwnProperty.call(页元素缓存, 当前页索引)) {
            return 页元素缓存[当前页索引];
        }
        const 页元素 = 取页元素 ? 取页元素(当前页索引) : null;
        页元素缓存[当前页索引] = 页元素;
        return 页元素;
    }

    // 滚动盒引用 + 滚动上限缓存。
    // scrollHeight / clientHeight 是布局属性，每个上拉帧重复读会强制同步布局，
    // 所以只在手势开始固定一次（手势期间内容尺寸视为稳定）。
    let 滚动盒缓存索引 = -1;
    let 滚动盒缓存元素 = null;
    let 滚动上限缓存 = null;
    function 取滚动盒元素() {
        const 当前页索引 = 状态.当前页;
        if (当前页索引 !== 滚动盒缓存索引 || !滚动盒缓存元素) {
            滚动盒缓存元素 = 取滚动盒 ? 取滚动盒(当前页索引) : null;
            滚动盒缓存索引 = 当前页索引;
            滚动上限缓存 = null;
        }
        return 滚动盒缓存元素;
    }
    function 是否贴顶() {
        const 滚动盒 = 取滚动盒元素();
        return !滚动盒 || 滚动盒.scrollTop <= 0;
    }
    function 是否贴底() {
        const 滚动盒 = 取滚动盒元素();
        if (!滚动盒) return true; // 内容不足一屏 → 视为同时贴顶与贴底
        if (滚动上限缓存 === null) {
            滚动上限缓存 = Math.max(0, 滚动盒.scrollHeight - 滚动盒.clientHeight);
        }
        return 滚动盒.scrollTop >= 滚动上限缓存 - 1;
    }

    // 写入一次拉伸：记下视觉值 + 直写当前页的 transform（不走 Vue）
    function 写入拉伸(拉伸量, 方向) {
        视觉拉伸量 = 拉伸量;
        视觉拉伸方向 = 方向;
        const 页元素 = 取当前页元素();
        if (页元素) 页元素.style.transform = 拼接变换字符串(拉伸量, 方向, 取页面尺寸());
    }

    // 复位一次拉伸（手势开始、以及取消/切页时用）
    function 复位拉伸() {
        视觉拉伸量 = 0;
        视觉拉伸方向 = "";
        已锁定拉伸方向 = "";
        const 页元素 = 取当前页元素();
        if (页元素) 页元素.style.transform = 拼接变换字符串(0, "", 取页面尺寸());
    }

    // 手势开始：解锁方向、复位视觉值与 DOM、接管滚动边界
    function 手势开始() {
        页元素缓存 = {}; // 期间可能发生过布局变化，元素引用重新取
        状态.跟手中 = true; // 按下的瞬间就关过渡，保证 1:1 跟手

        // 立即把当前页的 transform 复位，**直写 DOM、不等 Vue 渲染**。
        //
        // 为什么不能只靠「reactive 四量 = 0 触发渲染」：松手时会先把视觉值回填进
        // reactive（见 松手归位 ①），若新手势在随后的几帧内按下，这次的「四量 = 0」会与
        // 那次回填落在同一批 microtask 里 —— 净变化为 0，Vue 判定无更新、根本不重渲染，
        // DOM 就停在旧拉伸值上（表现为「按下瞬间画面还挂着上一次的拉伸，随后才跳回去」）。
        复位拉伸();

        // ── 以下整段都是**为纵向拉伸服务**的，纵向关掉时必须整段跳过 ──
        //
        // 这一段会把滚动盒的 overscroll-behavior 改成 none，而代码里**没有恢复逻辑** ——
        // 执行过一次就是永久的。纵向既然不接管滚动了，这么做只会反过来破坏原生滚动表现。
        if (!启用纵向拉伸) return;

        滚动盒缓存索引 = -1; // 滚动盒引用重新解析

        // 这是自定义拉伸实现，不能让 Android WebView 同时启动它自己的 EdgeEffect。
        // 原生过量回弹一旦在第一次越界时启动，会在整个触摸序列期间持续参与合成。
        const 滚动盒 = 取滚动盒元素();
        if (滚动盒) {
            滚动盒.style.overscrollBehavior = "none";
            滚动盒.style.overscrollBehaviorY = "none";
            滚动上限缓存 = Math.max(0, 滚动盒.scrollHeight - 滚动盒.clientHeight);
        }
    }

    // 纵向移动。返回 true = 本次移动已由拉伸接管（调用方不用再做任何事）；
    // 返回 false = 不满足拉伸条件，交还给浏览器做正常纵向滚动。
    //
    // 锁定流程：
    //   · 未锁定 → 只在「贴顶下拉 / 贴底上拉 且超过起始位移」时锁定方向；
    //     条件不满足就直接返回 false（不拉伸、也不锁定）
    //   · 已锁定 → **只按锁定方向取投影**算量。手指反向时投影变小 → 量连续减到 0
    //     然后停住，不会反方向拉伸（也就不会出现补偿位移跨 0 翻转）
    //
    // 注意 是否贴顶() / 是否贴底() 只在**锁定那一刻**判定一次：锁定后不再判定，
    // 否则「反向 → 浏览器开始滚动 → 条件失效」会让量瞬间归零、画面弹回一下（旧坑）。
    function 处理纵向拉伸(纵向位移) {
        // 关掉时返回 false = 不接管，调用方立刻 return → 纵向完全归浏览器滚动
        if (!启用纵向拉伸) return false;
        if (!已锁定拉伸方向) {
            if (纵向位移 > 拉伸起始位移 && 是否贴顶()) 已锁定拉伸方向 = "下拉";
            else if (纵向位移 < -拉伸起始位移 && 是否贴底()) 已锁定拉伸方向 = "上拉";
            if (!已锁定拉伸方向) return false;
        }
        // 投影 = 位移在锁定方向上的分量（反向移动时它会变小、乃至变负）
        const 沿锁定方向投影 = 已锁定拉伸方向 === "下拉" ? 纵向位移 : -纵向位移;
        写入拉伸(计算拉伸量(沿锁定方向投影 - 拉伸起始位移), 已锁定拉伸方向);
        return true;
    }

    // 横向越界（首页往右拉 / 末页往左拉）。返回 true = 拉伸接管（不做跟手平移）。
    // 是首页 / 是末页 由调用方判断（只有滑动模块知道页数与当前页）。
    //
    // 与纵向同一套锁定规则：锁定后手指反向只让量归零，不会变成反方向的拉伸。
    // 量归零后返回 false，把控制权交还给正常横向跟手平移（观感上就是「拉回原位后
    // 继续移动 → 开始正常翻页跟手」）。
    function 处理横向越界拉伸(横向位移, 是首页, 是末页) {
        // 横向目前是**开着**的，这行只是留个对称的开关口子。
        // ⚠️ 真要关掉时返回 **true**，不是 false —— true 的语义是「已接管 → 调用方不许再跟手平移」。
        // 返回 false 会让 滑动翻页 执行 `状态.拖动位移 = 横向位移`，轨道真的移出边界、
        // 露出轨道外的空白，比拉伸还难看。关掉拉伸的正确表现是「到边就拉不动」。
        if (!启用横向拉伸) return true;
        if (!已锁定拉伸方向) {
            if (是首页 && 横向位移 > 拉伸起始位移) 已锁定拉伸方向 = "右拉";
            else if (是末页 && 横向位移 < -拉伸起始位移) 已锁定拉伸方向 = "左拉";
            if (!已锁定拉伸方向) return false;
        }
        const 沿锁定方向投影 = 已锁定拉伸方向 === "右拉" ? 横向位移 : -横向位移;
        const 拉伸量 = 计算拉伸量(沿锁定方向投影 - 拉伸起始位移);
        if (拉伸量 <= 0) {
            写入拉伸(0, 已锁定拉伸方向); // 输出单位变换，保持 transform 结构恒定
            return false;
        }
        写入拉伸(拉伸量, 已锁定拉伸方向);
        return true;
    }

    // 松手结算：把跟手期间直写进 DOM 的拉伸值回填进 reactive，再让过渡接管。
    //
    // 为什么不能在同一帧清零（否则松手会「从初始位置附近开始」而不是原路返回）：
    // 清 拉伸量 会把 transform 从 scale3d(1.05, …) 瞬间设成 scale3d(1,1,1)。
    // Vue 的响应式更新是**异步批量**的：如果「切 transition」和「清拉伸」落进
    // 同一次刷新（或顺序颠倒），DOM 上就只体现最终值 —— 过渡的起点根本没被记录，
    // 浏览器只能从「随手抓到的当前值」开始播，看起来就是没在原位置、从初始态附近起步。
    //
    // 时序四步：① 回填 reactive（值等于 DOM 现值，不改变像素）
    //          → ② 等一帧上屏 → 切过渡（值不动，起点被正确记录）
    //          → ③ readback 强制 flush → ④ 再下一帧才归零。
    //
    // 归零用「代号」而非单一 rAF 句柄：取消一个 rAF 只能拦住"还没触发"的那个，
    // 若第一个 rAF 已触发、第二个刚排上，单句柄会漏掉第二个（竞态）。
    // 代号递增后，任何回调执行时都会核对「我是不是最新一代」，过期就静默退出。
    let 归零代号 = 0;
    function 作废归零回调() {
        归零代号++; // 让所有在途回调失效
    }
    function 松手归位() {
        状态.下拉量 = 视觉拉伸方向 === "下拉" ? 视觉拉伸量 : 0;
        状态.上拉量 = 视觉拉伸方向 === "上拉" ? 视觉拉伸量 : 0;
        状态.右拉量 = 视觉拉伸方向 === "右拉" ? 视觉拉伸量 : 0;
        状态.左拉量 = 视觉拉伸方向 === "左拉" ? 视觉拉伸量 : 0;
        视觉拉伸量 = 0;
        视觉拉伸方向 = "";
        已锁定拉伸方向 = ""; // 松手即解锁：下次手势重新判定方向

        const 本次代号 = ++归零代号;
        // ② 等一帧：让回填 patch 真正上屏（此时 transition 还是 none，画面纹丝不动）。
        requestAnimationFrame(() => {
            if (本次代号 !== 归零代号) return; // 已被新手势/新松手作废
            状态.跟手中 = false; // ③ 切过渡（值不动，起点被正确记录）
            requestAnimationFrame(() => {
                if (本次代号 !== 归零代号) return;
                const 页元素 = 取当前页元素();
                // ④ readback：把「新 transition + 当前 transform」钉成过渡起点
                if (页元素) void 页元素.offsetHeight;
                requestAnimationFrame(() => {
                    if (本次代号 !== 归零代号) return;
                    状态.下拉量 = 0;
                    状态.上拉量 = 0;
                    状态.右拉量 = 0;
                    状态.左拉量 = 0;
                    // 不需要「方向保留到动画播完」：方向由「哪个量非零」决定，
                    // 量归零后位移自然归零。
                });
            });
        });
    }

    // 每页的容器样式。
    //
    // 注意：非当前页也返回「单位变换」而不是 null ——
    // 返回 null 会让该元素丢掉 style 属性，transform 从 scale3d(…) 直接消失成 none，
    // 那一刻是硬跳变（翻页时旧页本来还带着拉伸，会"啪"地弹一下）。
    // 恒返回对象、值恒为单位变换，才能保证属性常驻、过渡两端始终可比。
    //
    // 本函数必须保持「纯读取」——不在渲染期写状态（那是副作用，可能引发循环更新）。
    function 页面样式(页索引) {
        const 是当前页 = 页索引 === 状态.当前页;
        let 当前拉伸量 = 0;
        let 当前方向 = "下拉";
        if (是当前页) {
            // 跟手期间拉伸值是**直写 DOM** 的，reactive 里还是 0。这里必须优先读视觉值，
            // 否则任何一次 Vue 渲染（例如用户同时轻微横向移动导致 拖动位移 变化）
            // 都会把 DOM 覆盖回单位变换。
            if (视觉拉伸量) {
                当前拉伸量 = 视觉拉伸量;
                当前方向 = 视觉拉伸方向 || "下拉";
            } else if (状态.下拉量) {
                当前拉伸量 = 状态.下拉量;
                当前方向 = "下拉";
            } else if (状态.上拉量) {
                当前拉伸量 = 状态.上拉量;
                当前方向 = "上拉";
            } else if (状态.右拉量) {
                当前拉伸量 = 状态.右拉量;
                当前方向 = "右拉";
            } else if (状态.左拉量) {
                当前拉伸量 = 状态.左拉量;
                当前方向 = "左拉";
            }
        }
        return {
            // transform 属性必须常驻（哪怕全是 1），否则松手时属性被移除，
            // 过渡失去起止两端可比，回弹会变成瞬跳。
            transform: 拼接变换字符串(当前拉伸量, 当前方向, 取页面尺寸()),
            transition: 状态.跟手中 ? "none" : "transform 0.34s cubic-bezier(0.22, 0.61, 0.36, 1)",
            // 不输出 transformOrigin：.页 的 CSS 已经是 center center（且恒不变），
            // 每帧少写一个键就少一次样式写入（拉伸是 120Hz 的高频路径）。
        };
    }

    // 视口尺寸变化（旋转 / 键盘弹出 / 切页后布局变化）时作废缓存的引用。
    // 尺寸本身不用清 —— 它是纯函数，每次从视口现取。
    function 作废尺寸缓存() {
        滚动盒缓存索引 = -1;
        滚动上限缓存 = null;
        页元素缓存 = {};
    }

    return {
        手势开始,
        处理纵向拉伸,
        处理横向越界拉伸,
        松手归位,
        作废归零回调,
        页面样式,
        作废尺寸缓存,
    };
}
