export default function 文库8(喵) {
  // ── ① 取工具 名字以 §7 保留标识符清单为准
  const {
    发起网络请求, Cookie, 编码处理, 解析文本,
    翻页, 发起下载, 记录日志, 源配置,
  } = 喵.工具;

  // ── ② 源内部 工具看不见也不干预
  const 主站 = "https://www.wenku8.net";
  const 下载站 = "https://dl.wenku8.com";
  const 载点列表 = [1, 2];
  // ansi 映射到 txt 是下载 URL 的格式参数 不是编码 协议 §4.1 特意拆开的
  const 载点类型 = { "utf-8": "utf8", utf8: "utf8", gbk: "txt", ansi: "txt", big5: "big5" };

  function 构建载点地址(书标识, 编码, 载点) {
    const 型 = 载点类型[编码] || "utf8";
    return `${下载站}/down.php?type=${型}&node=${载点}&id=${书标识}`;
  }

  function 构建分卷地址(书标识, 卷标识, 编码) {
    return `${下载站}/packtxt.php?aid=${书标识}&vid=${卷标识}&charset=${编码 || "utf-8"}`;
  }

  // 浏览器只有 TextEncoder UTF-8 产不出 GBK 字节 必须走原生 协议 §13 缺口 2
  async function 关键词转查询串(关键词) {
    const 字节 = await 编码处理.文本编码(关键词, "gbk");
    return [...字节].map((b) => `%${b.toString(16).toUpperCase().padStart(2, "0")}`).join("");
  }

  // ── ③ 解析 源自己的纯函数
  function 解析搜索结果(页面) {
    const 结果 = [];
    const 已处理 = new Set();
    for (const m of 页面.matchAll(/\/book\/(\d+)\.htm/g)) {
      const 书标识 = m[1];
      if (已处理.has(书标识)) continue;
      已处理.add(书标识);
      const 位置 = 页面.indexOf(`/book/${书标识}.htm`);
      if (位置 < 0) continue;
      // 结果块是书链往前 500 字内那个 width:373px 的 div 该站列表页固定结构
      const 起点 = Math.max(0, 位置 - 500);
      const 块起点 = 页面.substring(起点, 位置).lastIndexOf('<div style="width:373px');
      if (块起点 < 0) continue;
      const 块全 = 页面.substring(起点 + 块起点, 起点 + 块起点 + 1500);
      // 先切出这一本自己的块 那个 1500 字窗口很可能带上下一本的开头
      // 不切的话 includes 已完结 下架 会把下一本的状态算到这一本头上
      // 切法 找下一个 width:373px 容器
      const 下一个块 = 块全.indexOf('<div style="width:373px', 1);
      const 块 = 下一个块 > 0 ? 块全.substring(0, 下一个块) : 块全;
      const 取 = (re) => { const x = 块.match(re); return x ? x[1].trim() : ""; };

      // 书名必须单独取 只取书链自己那个 title
      // 原来扫块里第一个 title 撞上分类链接或上一本残留就取到空串
      // 空书名会进搜索缓存 之后每次命中都复现
      // 三级兜底 书链附近 title 到 链接文字 到 块里第一个 title
      const 链附近 = 页面.substring(Math.max(0, 位置 - 260), 位置 + 400);
      let 书名 = (链附近.match(/title="([^"]*)"/) || [])[1] || "";
      if (!书名) 书名 = (链附近.match(new RegExp(`/book/${书标识}\\.htm[^>]*>([^<]+)<`)) || [])[1] || "";
      if (!书名) 书名 = 取(/title="([^"]*)"/);
      if (!书名) continue;   // 认不出书名 宁少一条 也不要推一条空字段的

      const 标签匹配 = 块.match(/Tags:.*?<span[^>]*>([^<]+)<\/span>/);
      // 站点列表给的那一行 更新 2026-10-05 / 字数 141K / 连载中 有的还跟 已动画化
      // 一律用第一次正则匹配 别用 includes 判状态 后者会把块里出现过的词都算上
      const 更新日期 = 取(/更新:(\d{4}-\d{2}-\d{2})/);
      const 状态 = 取(/字数:[^\/<]*\/([^\/<\s]+)/) || (块.includes("已完结") ? "已完结" : (块.includes("连载中") ? "连载中" : ""));
      结果.push({
        标识: 书标识,
        书名: 书名.trim(),
        作者: 取(/作者:([^/]+)\//),
        分类: 取(/\/分类:([^<]+)/),
        状态,
        // 站上形如 141K 协议 §5 的字数本来就是字符串 原文照抄
        字数: 取(/字数:([^\/<\s]+)/),
        简介: 取(/简介:([^<]+)/),
        封面: 取(/src="(https?:\/\/img\.wenku8\.[^"]+)"/),
        标签: 标签匹配 ? 标签匹配[1].trim().split(/\s+/) : [],
        // 列表页看不出下架 本书公告只在详情页 这里一律 false
        // 权威判定在 获取详情函数 别用 块.includes 下架 搜索页尾通告会让它恒真
        已下架: false,
        // 最新话这一行的数据来源 列表页只给更新日期不给章名
        // 要章名得逐本拉详情 一本一个请求 本站 6 秒硬限速 列表里绝不能那么干
        // 按协议 §5 规范外进 扩展 与 获取详情函数 的 扩展.更新日期 同名同义
        扩展: { 更新日期 },
      });
    }
    return 结果;
  }

  function 取总页数(页面) {
    const m = 页面.match(/<em id="pagestats">(\d+)\/(\d+)<\/em>/);
    return m ? parseInt(m[2]) : 1;
  }

  // 这到底是不是搜索结果页 用来区分真的没搜到和站点根本没给页面
  // 有结果 一定带 id="pagestats" 和 /book/N.htm 书链
  // 真没搜到 站点给的是没有找到这类提示页
  // 都不是 站点返回了别的东西 CF 挑战页是 403 加 Just a moment
  // 不判这一下 挑战页会被解析出 0 条 和没搜到一模一样 页面还会重试一次 越试越封
  function 是不是结果页(页面) {
    return (
      /id="pagestats"/.test(页面) ||
      /\/book\/\d+\.htm/.test(页面) ||
      /没有找到|未找到|没有搜索到|搜索无结果/.test(页面)
    );
  }

  // 登录态凭据 文库8 登录成功种的是 jieqiVisitInfo
  // 值是 URL 编码的 jieqiUserLogin 加 jieqiUserId 访问过页面后才补 jieqiUserInfo
  // 只认后者 刚登录还没访问任何页面会被误判未登录 搜索直接被前置拦截
  async function 已登录() {
    const 全部 = await Cookie.获取Cookie();
    return 全部.some(
      (条) => (条.名 === "jieqiUserInfo" || 条.名 === "jieqiVisitInfo") && 条.值
    );
  }

  // 首页之后的分页收尾 源只给第几页到地址 和 怎么解析 翻页 间隔 限速 重试全归日轻喵
  //
  // 流式上报 选项.每页(批次 进度) 每抓完一页就交一次
  // 每页间隔 5 到 6 秒 5 页串行要 20 秒以上 全抓完再返回用户要盯空面板半分钟
  // 取搜索结果第 N 页 N 大于等于 2 绝不碰首页 原因见 搜索函数
  async function 取后面的页(基础地址, 想看的页, 请求选项, 选项) {
    const 每页 = typeof 选项?.每页 === "function" ? 选项.每页 : null;
    // 翻页也带登录态 2026-10-04 实测修正
    // 旧结论 带登录态翻页被拒 已过时 现在反过来了 匿名 page 大于等于 2 会 302 到 login.php
    // 带登录态 WebView 同源 fetch 有 cf_clearance 加 jieqi 才是 200
    // 别再传 Cookie 空串 让工具层照常带凭据
    const 翻页选项 = {
      ...请求选项,
      编码: "gbk",
    };
    const 响应 = await 发起网络请求(`${基础地址}&page=${想看的页}`, 翻页选项);
    const 页面 = 响应.文本 || "";
    if (!是不是结果页(页面)) {
      // 带上状态码 长度 开头 不然不是结果页有好几种成因 排查全靠猜
      const 跳转 = 响应.头?.location ? ` → ${响应.头.location}` : '';
      throw new Error(
        `站点没有返回搜索结果页（HTTP ${响应.状态}，${页面.length} 字${跳转}）—— 稍后再试`
      );
    }
    const 总页数 = Math.max(取总页数(页面), 1);
    const 本页结果 = 解析搜索结果(页面);
    每页?.(本页结果, { 页: 想看的页, 总页数 });
    return { 结果: 本页结果, 总页数, 页: 想看的页 };
  }

  // 第 1 页的收尾 解析首页 把共有几页告诉日轻喵
  async function 收尾(首页页面, 基础地址, 请求选项, 选项) {
    // 先确认这真是搜索结果页 挑战页异常页绝不能当成没搜到 否则会重试 越重试封得越死
    if (!是不是结果页(首页页面)) {
      throw new Error("站点没有返回搜索结果页（多半是人机验证没过）—— 换个网络或稍后再试");
    }
    const 每页 = typeof 选项?.每页 === "function" ? 选项.每页 : null;
    const 总页数 = Math.max(取总页数(首页页面), 1);
    const 首页结果 = 解析搜索结果(首页页面);
    每页?.(首页结果, { 页: 1, 总页数 });
    return { 结果: 首页结果, 总页数, 页: 1 };
  }

  // ── ④ 业务方法 局部函数声明 末尾引用导出
  // 登录 注册 是唯一不抛错的两处 用户输入校验 原因要回显到表单
  async function 登录函数(用户名, 密码, 选项 = {}) {
    // 不再先 GET 首页 过挑战 会自动建 origin POST 撞挑战时会先整页加载一次 那是纯浪费
    await 发起网络请求(`${主站}/login.php?do=submit&jumpurl=${主站}/index.php`, {
      方法: "POST",
      数据: { username: 用户名, password: 密码, usecookie: "315360000", action: "login" },
      不跟随重定向: true,
      信号: 选项.信号,
    });
    if (!(await 已登录())) return { 成功: false, 错误: "登录失败，请检查用户名和密码" };
    return { 成功: true };
  }

  async function 注册函数(用户名, 密码, 选项 = {}) {
    const 响应 = await 发起网络请求(`${主站}/register.php?do=submit`, {
      方法: "POST",
      数据: {
        username: 用户名, password: 密码, repassword: 密码,
        email: `${用户名}@muimui.com`, viewemail: "0", sex: "0", qq: "", url: "",
        action: "newuser",
      },
      编码: "gbk",
      不跟随重定向: true,
      信号: 选项.信号,
    });
    // 怎么算注册成功是本站特有判定 协议把它从工具层收回源自己
    if (响应.状态 >= 300 && 响应.状态 < 400) return { 成功: true };
    const 文本 = 响应.文本 || "";
    if (文本.includes("注册成功") || 文本.includes("注册完成")) return { 成功: true };
    if (!文本.includes("错误") && !文本.includes("失败") && !文本.includes("已存在")) return { 成功: true };
    const 错误匹配 = 文本.match(/<li[^>]*>([^<]+)<\/li>/) || 文本.match(/alert\("([^"]+)"\)/);
    return { 成功: false, 错误: 错误匹配 ? 错误匹配[1] : "注册失败" };
  }

  async function 搜索函数(关键词, 选项 = {}) {
    const { 信号, 搜索类型 = "articlename" } = 选项;
    // 不强制登录 实测本站搜索匿名完全可用 连 page 大于等于 2 都正常返回
    // 原先每搜一次先跑 首页 GET 加 登录 POST 白费 4 到 6 秒
    // 登录态没即时生效还会误判登录失败再重试一遍
    // 登录态有就带上 cookie 走凭据 没有也照样搜

    const 查询串 = await 关键词转查询串(关键词);
    const 基础地址 = `${主站}/modules/article/search.php?searchtype=${搜索类型}&searchkey=${查询串}`;
    const 请求选项 = { 不跟随重定向: true, 头: { Referer: `${主站}/` }, 信号 };

    // 要第 2 页及以后 直接取那一页 别再打首页
    // 首页是第 1 页专用 本站 302 有精确匹配直跳详情的特例 只有第 1 页要管
    // 多打那次首页会撞站点搜索冷却 实测连发两次 第二次拿到 929 字出现错误页 翻页永远失败
    const 想看的页 = Math.max(1, Number(选项?.页 ?? 1));
    if (想看的页 >= 2) return 取后面的页(基础地址, 想看的页, 请求选项, 选项);

    // 首页单独走 本站 302 有两种含义 精确匹配直跳详情页 未登录跳 login.php
    // 都不能当普通列表页处理
    const 首页 = await 发起网络请求(`${基础地址}&page=1`, 请求选项);

    // 403 或 429 是站点要人机验证 CF 不是没搜到
    // 请求过密时连首页都 403 加 Just a moment
    // 换账号没用 CF 认 IP 不认账号 只能换网络或等它过期
    if (首页.状态 === 403 || 首页.状态 === 429) {
      throw new Error(`站点要求人机验证（HTTP ${首页.状态}）—— 换个网络（切 WiFi / 流量）或等一会儿再搜`);
    }

    if (首页.状态 >= 300 && 首页.状态 < 400) {
      const 跳转 = 首页.头.location || "";       // 头键一律小写
      if (跳转.includes("login.php")) throw new Error("登录态已过期，请重新登录");
      const 命中 = 跳转.match(/\/book\/(\d+)\.htm/);
      if (命中) {
        const 详情 = await 获取详情函数(命中[1], { 信号 });
        // 规范外的字段一律进 扩展 协议 §5
        const 单条 = { ...详情, 扩展: { ...(详情.扩展 || {}), 精确匹配: true } };
        // 精确匹配只有一条 同样走 每页 让页面不必区分两种返回路径
        if (typeof 选项.每页 === "function") 选项.每页([单条], { 页: 1, 总页数: 1 });
        return { 结果: [单条], 总页数: 1 };
      }
      const 重发 = 跳转.startsWith("http") ? 跳转 : 主站 + 跳转;
      const 二次 = await 发起网络请求(重发, { ...请求选项, 编码: "gbk" });
      return 收尾(二次.文本, 基础地址, 请求选项, 选项);
    }

    // 没给编码时 文本 是 null 由源自己解 这个站列表页是 GBK
    const 页面 = 首页.文本 ?? await 编码处理.文本解码(首页.原始, "gbk");
    return 收尾(页面, 基础地址, 请求选项, 选项);
  }

  async function 获取详情函数(书标识, 选项 = {}) {
    const 响应 = await 发起网络请求(`${主站}/book/${书标识}.htm`, { 编码: "gbk", 信号: 选项.信号 });
    const 页面 = 响应.文本;
    const 取 = (re) => { const m = 页面.match(re); return m ? m[1].trim() : ""; };
    return {
      标识: 书标识,
      书名: 取(/<b>([^<]+)<\/b>/) || "未知",
      作者: 取(/小说作者[：:]([^<]+)/),
      分类: 取(/文库分类[：:]([^<]+)/),
      状态: 取(/文章状态[：:]([^<]+)/),
      // 简介正文含换行 正文里 br 后面还跟 \r\n
      // 原来的 (.*?) 没带 s 标志 . 不跨行 正文一换行就一个字符都取不到 简介永远是空串
      // 改成从标签一路跨到正文那个 span
      简介: 解析文本.HTML转文本(取(/内容简介[：:][\s\S]*?<span[^>]*>([\s\S]*?)<\/span>/)),
      封面: 取(/src="(https?:\/\/img\.wenku8\.[^"]+)"/),   // 封面只在这里
      标签: [],
      字数: 取(/全文长度[：:]([^<]+)/),
      // 已下架在源里判定 判定归源 限制只在前端
      // 原来的 页面.includes 下架 恒为真 页面底部站点通告里就有下架二字
      // 可靠判据是本书公告里的不再提供 实测 471 刀剑神域 命中 在售书不命中
      已下架: /不再提供/.test(页面),
      扩展: {
        更新日期: 取(/最后更新[：:]([^<]+)/),
      },
    };
  }

  // ── 小说目录页 真正的目录在这儿 不是分卷下载页
  //
  // URL 主站/novel/桶/书标识/index.htm 桶 = floor(书标识/1000)
  // 站点按千位分桶 那个 0 不是分类号 是这本书落在第几个千位
  // 471 到 0 1115 到 1 3478 到 3 4076 到 4 拿错桶直接 404 出错啦
  //
  // 为什么不拿分卷下载页 packshow 当目录
  //   packshow 只给卷 给不出章
  //   下架书整个失效 471 返回 200 加 919 字节 出现错误 页 零个 td class odd
  //   同一本书目录页有 42 卷 464 章 目录一直都在 只是不在 packshow 上
  //
  // 这一页一次请求给两样东西
  //   td class vcss 卷名 加 vid 分卷下载要它
  //   td class ccss 章名 加 cid 逐章阅读要它
  // 章节链接是相对的 完整地址是 /novel/桶/书标识/cid.htm

  /** 书标识 到 目录页地址 桶 = floor(书标识 / 1000) */
  function 目录页地址(书标识, 桶) {
    return `${主站}/novel/${桶}/${书标识}/index.htm`;
  }

  // 解析目录页 到 章级列表 名称 标识 卷 卷标识
  // 标识 是 cid 透传令牌 逐章阅读和下载原样传回
  // 卷 卷标识 是这一章属哪卷 以及那卷的 vid
  // 顺序就是站点给的 不要自己重排
  function 解析目录页(页面) {
    const 结果 = [];
    let 当前卷 = '';
    let 当前卷标识 = '';
    // 只认表格里这两种格子 vcss 卷头带 vid ccss 章带相对链接
    const 格子 = /<td class="(vcss|ccss)"([^>]*)>(?:<a href="(\d+)\.htm">([^<]+)<\/a>|([^<]+))<\/td>/g;
    for (const 命中 of 页面.matchAll(格子)) {
      const 类型 = 命中[1];
      if (类型 === 'vcss') {
        当前卷标识 = (String(命中[2]).match(/vid="(\d+)"/) || [])[1] || '';
        当前卷 = String(命中[5] || '').trim();
        continue;
      }
      const 章标识 = 命中[3] || '';
      if (!章标识) continue;
      const 章名 = String(命中[4] || '').trim();
      结果.push({
        名称: 章名 || `第 ${结果.length + 1} 章`,
        标识: 章标识,
        卷: 当前卷,
        卷标识: 当前卷标识,
      });
    }
    return 结果;
  }

  // 取目录 协议 §5 ii 的 获取目标资源章节列表
  // 这里给章级目录 换掉了原来的 packshow 分卷列表
  // 拿不到就抛错说清楚 绝不静默返回空数组 空数组在页面上会被当成这本书没目录
  async function 获取章节列表函数(书标识, 选项 = {}) {
    const 桶 = Math.floor(Number(书标识) / 1000);
    const 地址 = 目录页地址(书标识, 桶);
    const 响应 = await 发起网络请求(地址, { 编码: "gbk", 信号: 选项.信号 });
    const 页面 = 响应.文本 || "";
    if (!页面.includes('class="ccss"')) {
      throw new Error(
        `站点没给这本书的小说目录（HTTP ${响应.状态}，${页面.length} 字，${地址}）—— 稍后再试`
      );
    }
    const 章列表 = 解析目录页(页面);
    if (!章列表.length) throw new Error("站点的小说目录页是空的 —— 稍后再试");
    return 章列表;
  }

  async function 下载函数(书标识, 书名, 模式, 选项 = {}) {
    const { 信号, 编码 } = 选项;
    const 请求头 = { Referer: `${主站}/` };

    if (模式 === "全文") {
      const 首选 = 选项.载点 || await 源配置.获取("载点", 1);
      const 顺序 = [首选, ...载点列表.filter((编号) => 编号 !== 首选)];
      记录日志(`全文下载：${书名}（载点顺序 ${顺序.join(" → ")}）`);
      return await 发起下载({
        书名,
        // 基址不带 node 由 备用url 提供 否则会拼成 node=1&node=2 服务端取哪个不确定
        下载url: `${下载站}/down.php?type=${载点类型[编码] || "utf8"}&id=${书标识}`,
        备用url: (第几次) => `&node=${顺序[第几次] ?? 顺序[0]}`,
        文件名: `${书名}.txt`,
        请求头,
        进度: ["百分比", "速度", "剩余"],
        续传键: `wenku8/${书标识}/全文`,
        信号,
      });
    }

    if (模式 === "分卷") {
      const 分卷 = 选项.分卷;
      if (!分卷 || 分卷.length === 0) throw new Error("未指定分卷");
      return await 发起下载({
        书名,
        任务列表: 分卷.map((卷) => ({
          说明: 卷.名称,
          地址: 构建分卷地址(书标识, 卷.标识, 编码),
          文件名: `${卷.名称}.txt`,
        })),
        子目录: ["分卷"],
        请求头,
        进度: ["百分比", "卷进度", "速度", "剩余"],
        并发: { 任务数: 1, 任务间隔: 1000 },
        续传键: `wenku8/${书标识}/分卷`,
        信号,
      });
    }

    throw new Error(`未知下载模式：${模式}`);
  }

  // ── ⑤ 末尾只做引用导出 方法名逐字 与 元信息.能力 一一对应
  return {
    标识: 元信息.标识,
    名称: 元信息.名称,
    资源搜索: 搜索函数,
    获取资源详情: 获取详情函数,
    获取目标资源章节列表: 获取章节列表函数,
    资源下载: 下载函数,
    登录至源平台: 登录函数,
    注册源平台账号: 注册函数,
  };
}

