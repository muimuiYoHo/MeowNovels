fn main() {
    // 「初始数据」（`client/gui/src/资源/初始数据/`）是**编译期**整棵树嵌进二进制的
    // （`include_dir!`，见 platform.android.rs）。但 cargo 并不知道存在这个依赖 ——
    // 不在这里声明的话，改了初始数据、cargo 认为「源码没变」直接跳过编译，
    // **新加的数据文件根本进不了二进制**。
    //
    // 现象极具迷惑性：文件明明在仓库里、`初始化应用存储` 也照常跑了，就是 App 里死活没有。
    // 2026-09-30 加 `数据/源/源注册.json` 时踩到 —— 当时是靠「顺手改了一行 Rust 代码」
    // 凑巧重编才成功的，纯属运气。
    //
    // ⚠️ 路径相对 src-tauri/；要声明**目录**本身，新增文件才能触发重编。
    println!("cargo:rerun-if-changed=../src/资源/初始数据");
    tauri_build::build()
}
